const Config = z.strictObject({});

type Config = z.infer<typeof Config>;

class FsharpCodeGenerator implements CodeGenerator<Config> {
  readonly id = "skir-fsharp-gen";
  readonly configType = Config;

  generateCode(input: CodeGenerator.Input<Config>): CodeGenerator.Output {
    const keyedArrayContext = new KeyedArrayContext(
      input.modules,
      input.recordMap,
    );
    const sortedModules = sortModulesTopologically(input.modules);
    const lines: string[] = [
      "//  ______                        _               _  _  _",
      "//  |  _  \\                      | |             | |(_)| |",
      "//  | | | |  ___    _ __    ___  | |_    ___   __| | _ | |_",
      "//  | | | | / _ \\  | '_ \\  / _ \\ | __|  / _ \\ / _` || || __|",
      "//  | |/ / | (_) | | | | || (_) || |_  |  __/| (_| || || |_ ",
      "//  |___/   \\___/  |_| |_| \\___/  \\__|  \\___| \\__,_||_| \\__|",
      "//",
      "// Generated by skir-fsharp-gen",
      "// Home: https://skir.build/docs/fsharp",
      "//",
      "// To install the Skir client library, run:",
      "//   dotnet add package skir_client",
      "",
      "namespace global",
      "",
      '#nowarn "0346"',
      '#nowarn "0040"',
      "",
    ];

    for (const module of sortedModules) {
      const modGen = new FsharpModuleGenerator(
        module,
        modulePathToFsharpModuleName(module.path),
        input.recordMap,
        keyedArrayContext,
      );
      lines.push(modGen.generate());
    }

    return {
      files: [
        {
          path: "Skirout.fs",
          code: lines.join("\n"),
        },
      ],
    };
  }
}

function sortModulesTopologically(modules: readonly Module[]): Module[] {
  const pathToModule = new Map<string, Module>();
  for (const mod of modules) {
    pathToModule.set(mod.path, mod);
  }
  const visited = new Set<string>();
  const sorted: Module[] = [];

  function visit(mod: Module): void {
    if (visited.has(mod.path)) return;
    visited.add(mod.path);
    for (const importedPath of Object.keys(mod.pathToImportedNames)) {
      const dep = pathToModule.get(importedPath);
      if (dep) {
        visit(dep);
      }
    }
    sorted.push(mod);
  }

  for (const mod of modules) {
    visit(mod);
  }
  return sorted;
}

class FsharpModuleGenerator {
  private readonly lines: string[] = [];
  private readonly typeSpeller: TypeSpeller;
  private readonly fieldNameMapCache = new Map<
    RecordKey,
    Map<string, string>
  >();

  constructor(
    private readonly module: Module,
    private readonly moduleName: string,
    recordMap: ReadonlyMap<RecordKey, RecordLocation>,
    private readonly keyedArrayContext: KeyedArrayContext,
  ) {
    this.typeSpeller = new TypeSpeller(recordMap, module.path);
  }

  generate(): string {
    this.lines.push(`// ${"=".repeat(76)}`);
    this.lines.push(`// Module ${this.module.path}`);
    this.lines.push(`// ${"=".repeat(76)}`);
    this.lines.push(`module rec ${this.moduleName} =`);

    const moduleRecords = this.module.records.filter(
      (r) => r.modulePath === this.module.path,
    );

    let hasContent = false;

    for (const record of moduleRecords) {
      hasContent = true;
      this.writeRecord(record);
    }

    if (moduleRecords.length > 0) {
      this.writeModuleInit(moduleRecords);
    }

    if (this.module.methods.length > 0) {
      hasContent = true;
      this.writeModuleMethods();
    }

    if (this.module.constants.length > 0) {
      hasContent = true;
      this.writeModuleConstants();
    }

    if (!hasContent) {
      this.lines.push("    do ()");
    }

    this.lines.push("");
    return this.lines.join("\n");
  }

  private writeRecord(record: RecordLocation): void {
    const name = getTypeName(record);
    const { recordType } = record.record;

    this.lines.push("");
    this.lines.push(
      `    // ${recordType} ${record.recordAncestors.map((r) => r.name.text).join(".")}`,
    );

    if (recordType === "struct") {
      this.writeStruct(record, name);
    } else {
      this.writeEnum(record, name);
    }
  }

  private writeStruct(record: RecordLocation, name: string): void {
    const fields = record.record.fields.filter((f) => f.type !== undefined);

    this.lines.push(...this.formatDocAsXmlSummary(record.record.doc, "    "));
    this.lines.push("    [<CustomEquality; NoComparison>]");
    this.lines.push(`    type ${name} =`);
    this.lines.push("        {");
    for (const field of fields) {
      const propName = toFieldPropertyName(field, name);
      const fieldType = this.typeSpeller.getFsharpFieldType(field);
      this.lines.push(...this.formatDocAsXmlSummary(field.doc, "            "));
      this.lines.push(`            ${propName}: ${fieldType}`);
    }
    this.lines.push(
      `            _unrecognized: global.SkirClient.Internal.UnrecognizedFields<${name}>`,
    );
    this.lines.push("        }");
    this.lines.push("        with");

    // Equals
    this.lines.push("        override this.Equals(obj: obj) : bool =");
    this.lines.push("            match obj with");
    this.lines.push(`            | :? ${name} as other ->`);
    if (fields.length === 0) {
      this.lines.push("                true");
    } else {
      const eqExprs = fields.map((field) => {
        const propName = toFieldPropertyName(field, name);
        return this.typeSpeller.getFieldEqualsExpr(
          field,
          `this.${propName}`,
          `other.${propName}`,
        );
      });
      this.lines.push(
        `                ${eqExprs.join(" &&\n                ")}`,
      );
    }
    this.lines.push("            | _ -> false");

    // GetHashCode
    this.lines.push("        override this.GetHashCode() : int =");
    if (fields.length === 0) {
      this.lines.push("            0");
    } else {
      this.lines.push("            let mutable h = 17");
      for (const field of fields) {
        const propName = toFieldPropertyName(field, name);
        const hashExpr = this.typeSpeller.getFieldHashExpr(
          field,
          `this.${propName}`,
        );
        this.lines.push(`            h <- h * 31 + (${hashExpr})`);
      }
      this.lines.push("            h");
    }

    // ToString
    this.lines.push(
      `        override this.ToString() : string = ${name}.Serializer.ToJson(this, readable = true)`,
    );

    // Default
    this.lines.push(
      `        static let _default : global.System.Lazy<${name}> =`,
    );
    this.lines.push(`            global.System.Lazy<${name}>(fun () ->`);
    this.lines.push("                {");
    for (const field of fields) {
      const propName = toFieldPropertyName(field, name);
      const defaultExpr = this.typeSpeller.getFieldDefaultExpr(field);
      this.lines.push(`                    ${propName} = ${defaultExpr}`);
    }
    this.lines.push("                    _unrecognized = null");
    this.lines.push("                }");
    this.lines.push("            )");
    this.lines.push(`        static member Default : ${name} = _default.Value`);

    // Create helper with optional arguments
    if (fields.length === 0) {
      this.lines.push(
        `        static member Create() : ${name} = ${name}.Default`,
      );
    } else {
      const params = fields
        .map((field) => {
          const paramName = toFieldParamName(field);
          const fieldType = this.typeSpeller.getFsharpFieldType(field);
          return `?${paramName}: ${fieldType}`;
        })
        .join(", ");
      this.lines.push(`        static member Create(${params}) : ${name} =`);
      this.lines.push("            {");
      for (const field of fields) {
        const propName = toFieldPropertyName(field, name);
        const paramName = toFieldParamName(field);
        const defaultExpr = this.typeSpeller.getFieldDefaultExpr(field);
        this.lines.push(
          `                ${propName} = defaultArg ${paramName} (${defaultExpr})`,
        );
      }
      this.lines.push("                _unrecognized = null");
      this.lines.push("            }");
    }

    // Serializer property
    this.lines.push(
      `        static member Serializer : global.SkirClient.Serializer<${name}> =`,
    );
    this.lines.push("            ModuleInit_.EnsureInit()");
    this.lines.push(`            ModuleInit_.${name}_Serializer`);

    // Keyed array indexers on item struct
    const keyedArrayIndexers = this.computeStructIndexerInfos(record);
    for (const indexer of keyedArrayIndexers) {
      this.lines.push(
        `        static member val internal ${indexer.indexerName} : global.SkirClient.Internal.Indexer<${name}, ${indexer.keyType}> = global.SkirClient.Internal.Indexer<${name}, ${indexer.keyType}>(global.System.Func<${name}, ${indexer.keyType}>(${indexer.keySelector}))`,
      );
    }

    // Keyed array FindBy* methods on container struct
    for (const field of fields) {
      if (!field.type || field.type.kind !== "array" || !field.type.key) {
        continue;
      }

      const propertyName = toFieldPropertyName(field, name);
      const keySpec = this.keyedArrayContext.getKeySpecForArrayType(field.type);
      if (!keySpec || field.type.item.kind !== "record") {
        continue;
      }

      const keyType = this.getFsharpMapKeyType(field.type.key.keyType);
      if (!keyType) {
        continue;
      }

      const itemRecord = this.typeSpeller.recordMap.get(field.type.item.key);
      if (!itemRecord || itemRecord.record.recordType !== "struct") {
        continue;
      }

      const itemIndexers = this.computeStructIndexerInfos(itemRecord);
      const keyExtractor = this.getFieldPathExtractor(keySpec.fieldPath);
      const itemIndexer = itemIndexers.find(
        (indexer) => indexer.keyExtractor === keyExtractor,
      );
      if (!itemIndexer) {
        continue;
      }

      const itemType = this.typeSpeller.getFsharpType(field.type.item);
      const itemDefaultExpr = this.typeSpeller.getDefaultExpr(field.type.item);
      const itemIndexerRef = `${itemType}.${itemIndexer.indexerName}`;
      const keyPathName = this.getFieldPathMemberSuffix(keySpec.fieldPath);
      const findByKeyName = `${propertyName}_FindBy${keyPathName}`;
      const findByKeyOrDefaultName = `${propertyName}_FindBy${keyPathName}OrDefault`;

      this.lines.push(
        `        /// <summary>Finds an item in ${propertyName} by ${keyPathName}, or returns None if not found.</summary>`,
      );
      this.lines.push(
        `        member this.${findByKeyName}(key: ${keyType}) : option<${itemType}> =`,
      );
      this.lines.push(
        `            let indexed = ${itemIndexerRef}.Index(this.${propertyName})`,
      );
      this.lines.push("            let mutable idx = 0");
      this.lines.push(
        `            if indexed.TryGetValue(key, &idx) then Some(this.${propertyName}.[idx]) else None`,
      );

      this.lines.push(
        `        /// <summary>Finds an item in ${propertyName} by ${keyPathName}, or returns the default value if not found.</summary>`,
      );
      this.lines.push(
        `        member this.${findByKeyOrDefaultName}(key: ${keyType}) : ${itemType} =`,
      );
      this.lines.push(
        `            let indexed = ${itemIndexerRef}.Index(this.${propertyName})`,
      );
      this.lines.push("            let mutable idx = 0");
      this.lines.push(
        `            if indexed.TryGetValue(key, &idx) then this.${propertyName}.[idx] else ${itemDefaultExpr}`,
      );
    }
  }

  private writeEnum(record: RecordLocation, name: string): void {
    const variants = record.record.fields;
    const variantInfos = variants.map((v) => ({
      variant: v,
      caseName: toVariantCaseName(v, name),
      upperCamel: convertCase(v.name.text, "UpperCamel"),
    }));

    const kindTypeName = `${name}_Kind`;

    // Emit Kind enum for keyed array / kind inspection
    this.lines.push(`    type ${kindTypeName} =`);
    this.lines.push("        | Unknown = 0");
    variantInfos.forEach(({ variant, upperCamel }, i) => {
      const kindCase = variant.type ? `${upperCamel}Wrapper` : upperCamel;
      this.lines.push(`        | ${kindCase} = ${i + 1}`);
    });

    this.lines.push("");
    this.lines.push(...this.formatDocAsXmlSummary(record.record.doc, "    "));
    this.lines.push("    [<CustomEquality; NoComparison>]");
    this.lines.push(`    type ${name} =`);
    this.lines.push(
      `        | Unknown of global.SkirClient.Internal.UnrecognizedVariant<${name}>`,
    );
    for (const { variant, caseName } of variantInfos) {
      this.lines.push(...this.formatDocAsXmlSummary(variant.doc, "        "));
      if (variant.type) {
        const payloadType = this.typeSpeller.getFsharpType(variant.type);
        this.lines.push(`        | ${caseName} of ${payloadType}`);
      } else {
        this.lines.push(`        | ${caseName}`);
      }
    }
    this.lines.push("        with");

    // Kind property
    this.lines.push(`        member this.Kind : ${kindTypeName} =`);
    this.lines.push("            match this with");
    this.lines.push(`            | Unknown _ -> ${kindTypeName}.Unknown`);
    for (const { variant, caseName, upperCamel } of variantInfos) {
      const kindCase = variant.type ? `${upperCamel}Wrapper` : upperCamel;
      if (variant.type) {
        this.lines.push(
          `            | ${caseName} _ -> ${kindTypeName}.${kindCase}`,
        );
      } else {
        this.lines.push(
          `            | ${caseName} -> ${kindTypeName}.${kindCase}`,
        );
      }
    }

    // Equals
    this.lines.push("        override this.Equals(obj: obj) : bool =");
    this.lines.push("            match obj with");
    this.lines.push(`            | :? ${name} as other ->`);
    this.lines.push("                match this, other with");
    this.lines.push("                | Unknown _, Unknown _ -> true");
    for (const { variant, caseName } of variantInfos) {
      if (variant.type) {
        const eqExpr = this.typeSpeller.getValueEqualsExpr(
          variant.type,
          "a",
          "b",
        );
        this.lines.push(
          `                | ${caseName} a, ${caseName} b -> ${eqExpr}`,
        );
      } else {
        this.lines.push(`                | ${caseName}, ${caseName} -> true`);
      }
    }
    if (variantInfos.length > 0) {
      this.lines.push("                | _ -> false");
    }
    this.lines.push("            | _ -> false");

    // GetHashCode
    this.lines.push("        override this.GetHashCode() : int =");
    this.lines.push("            match this with");
    this.lines.push("            | Unknown _ -> 0");
    variantInfos.forEach(({ variant, caseName }, i) => {
      const ord = i + 1;
      if (variant.type) {
        const hashExpr = this.typeSpeller.getValueHashExpr(variant.type, "v");
        this.lines.push(
          `            | ${caseName} v -> (${ord} * 31) + (${hashExpr})`,
        );
      } else {
        this.lines.push(`            | ${caseName} -> ${ord}`);
      }
    });

    // ToString
    this.lines.push(
      `        override this.ToString() : string = ${name}.Serializer.ToJson(this, readable = true)`,
    );

    // UnknownDefault / Default
    this.lines.push(
      `        static let _unknownDefault : ${name} = Unknown null`,
    );
    this.lines.push(
      `        static member UnknownDefault : ${name} = _unknownDefault`,
    );
    this.lines.push(
      `        static member Default : ${name} = _unknownDefault`,
    );

    // Serializer
    this.lines.push(
      `        static member Serializer : global.SkirClient.Serializer<${name}> =`,
    );
    this.lines.push("            ModuleInit_.EnsureInit()");
    this.lines.push(`            ModuleInit_.${name}_Serializer`);
  }

  private writeModuleMethods(): void {
    const { methods } = this.module;
    if (methods.length === 0) return;

    this.lines.push("");
    this.lines.push("    module Methods =");
    for (const method of methods) {
      const propName = convertCase(method.name.text, "UpperCamel");
      const requestType = this.typeSpeller.getFsharpType(method.requestType!);
      const responseType = this.typeSpeller.getFsharpType(method.responseType!);
      const requestSerExpr = this.typeSpeller.getSerializerExpr(
        method.requestType!,
      );
      const responseSerExpr = this.typeSpeller.getSerializerExpr(
        method.responseType!,
      );
      const methodType = `global.SkirClient.Method<${requestType}, ${responseType}>`;
      this.lines.push(`        type ${propName}_Holder_ private () =`);
      this.lines.push(
        `            static let _lazy : global.System.Lazy<${methodType}> =`,
      );
      this.lines.push(
        `                global.System.Lazy<${methodType}>(fun () ->`,
      );
      this.lines.push(
        `                    global.SkirClient.Method<${requestType}, ${responseType}>(`,
      );
      this.lines.push(
        `                        ${JSON.stringify(method.name.text)},`,
      );
      this.lines.push(`                        ${method.number},`);
      this.lines.push(
        `                        ${JSON.stringify(this.getDocText(method.doc))},`,
      );
      this.lines.push(`                        ${requestSerExpr},`);
      this.lines.push(`                        ${responseSerExpr}`);
      this.lines.push("                    )");
      this.lines.push("                )");
      this.lines.push(
        `            static member Value : ${methodType} = _lazy.Value`,
      );
      this.lines.push(...this.formatDocAsXmlSummary(method.doc, "        "));
      this.lines.push(
        `        let ${propName} : ${methodType} = ${propName}_Holder_.Value`,
      );
    }
  }

  private writeModuleConstants(): void {
    const { constants } = this.module;
    if (constants.length === 0) return;

    this.lines.push("");
    this.lines.push("    module Consts =");
    for (const constant of constants) {
      const propName = convertCase(constant.name.text, "UpperCamel");
      const type = constant.type!;
      const fsharpType = this.typeSpeller.getFsharpType(type);
      const serExpr = this.typeSpeller.getSerializerExpr(type);
      const jsonLiteral = JSON.stringify(
        JSON.stringify(constant.valueAsDenseJson),
      );
      this.lines.push(`        type ${propName}_Holder_ private () =`);
      this.lines.push(
        `            static let _lazy : global.System.Lazy<${fsharpType}> =`,
      );
      this.lines.push(
        `                global.System.Lazy<${fsharpType}>(fun () -> (${serExpr}).FromJson(${jsonLiteral}))`,
      );
      this.lines.push(
        `            static member Value : ${fsharpType} = _lazy.Value`,
      );
      this.lines.push(...this.formatDocAsXmlSummary(constant.doc, "        "));
      this.lines.push(
        `        let ${propName} : ${fsharpType} = ${propName}_Holder_.Value`,
      );
    }
  }

  private writeModuleInit(moduleRecords: readonly RecordLocation[]): void {
    this.lines.push("");
    this.lines.push("    module internal ModuleInit_ =");

    for (const record of moduleRecords) {
      if (record.record.recordType === "struct") {
        this.writeModuleInitBuilder(record);
      }
    }

    for (const record of moduleRecords) {
      this.writeModuleInitAdapterFields(record);
    }

    this.lines.push("        let private _lazy : global.System.Lazy<bool> =");
    this.lines.push("            global.System.Lazy<bool>(fun () ->");
    for (const record of moduleRecords) {
      this.writeModuleInitAdapterInit(record);
    }
    this.lines.push("                true");
    this.lines.push("            )");
    this.lines.push("        let EnsureInit () : unit = ignore _lazy.Value");
  }

  private writeModuleInitBuilder(record: RecordLocation): void {
    const name = getTypeName(record);
    const builderName = `${name}_builder`;
    const fields = record.record.fields.filter((f) => f.type !== undefined);

    this.lines.push(`        type ${builderName}() =`);
    for (const field of fields) {
      const propertyName = toFieldPropertyName(field, name);
      const fieldType = this.typeSpeller.getFsharpFieldType(field);
      const defaultExpr = this.typeSpeller.getFieldDefaultExpr(field);
      this.lines.push(
        `            member val ${propertyName} : ${fieldType} = ${defaultExpr} with get, set`,
      );
    }
    this.lines.push(
      `            member val _unrecognized : global.SkirClient.Internal.UnrecognizedFields<${name}> = null with get, set`,
    );
  }

  private writeModuleInitAdapterFields(record: RecordLocation): void {
    const name = getTypeName(record);
    const qualifiedName = record.recordAncestors
      .map((r) => r.name.text)
      .join(".");
    const modulePath = record.modulePath;
    const docText = this.getDocText(record.record.doc);

    if (record.record.recordType === "struct") {
      const builderName = `${name}_builder`;
      const fields = record.record.fields.filter((f) => f.type !== undefined);
      const buildFields = fields
        .map((f) => {
          const propName = toFieldPropertyName(f, name);
          return `${propName} = b.${propName}`;
        })
        .join("; ");
      const buildBody = buildFields
        ? `{ ${buildFields}; _unrecognized = b._unrecognized }`
        : `{ _unrecognized = b._unrecognized }`;

      this.lines.push(
        `        let ${name}_Adapter : global.SkirClient.Internal.StructAdapter<${name}, ${builderName}> =`,
      );
      this.lines.push(
        `            global.SkirClient.Internal.StructAdapter<${name}, ${builderName}>(`,
      );
      this.lines.push(`                ${name}.Default,`);
      this.lines.push(`                ${JSON.stringify(modulePath)},`);
      this.lines.push(`                ${JSON.stringify(qualifiedName)},`);
      this.lines.push(`                ${JSON.stringify(docText)},`);
      this.lines.push(
        `                global.System.Func<${builderName}>(fun () -> ${builderName}()),`,
      );
      this.lines.push(
        `                global.System.Func<${builderName}, ${name}>(fun b -> ${buildBody}),`,
      );
      this.lines.push(
        `                global.System.Func<${name}, global.SkirClient.Internal.UnrecognizedFields<${name}>>(fun x -> x._unrecognized),`,
      );
      this.lines.push(
        `                global.System.Action<${builderName}, global.SkirClient.Internal.UnrecognizedFields<${name}>>(fun b v -> b._unrecognized <- v)`,
      );
      this.lines.push("            )");
      this.lines.push(
        `        let ${name}_Serializer : global.SkirClient.Serializer<${name}> = ${name}_Adapter.ToSerializer()`,
      );
      return;
    }

    this.lines.push(
      `        let ${name}_Adapter : global.SkirClient.Internal.EnumAdapter<${name}> =`,
    );
    this.lines.push(
      `            global.SkirClient.Internal.EnumAdapter<${name}>(`,
    );
    this.lines.push(
      `                global.System.Func<${name}, int>(fun x -> int x.Kind),`,
    );
    this.lines.push(
      `                global.System.Func<global.SkirClient.Internal.UnrecognizedVariant<${name}>, ${name}>(fun u -> ${name}.Unknown u),`,
    );
    this.lines.push(
      `                global.System.Func<${name}, global.SkirClient.Internal.UnrecognizedVariant<${name}>>(fun x -> match x with | ${name}.Unknown u -> u${record.record.fields.length > 0 ? " | _ -> null" : ""}),`,
    );
    this.lines.push(`                ${name}.UnknownDefault,`);
    this.lines.push(`                ${JSON.stringify(modulePath)},`);
    this.lines.push(`                ${JSON.stringify(qualifiedName)},`);
    this.lines.push(`                ${JSON.stringify(docText)}`);
    this.lines.push("            )");
    this.lines.push(
      `        let ${name}_Serializer : global.SkirClient.Serializer<${name}> = ${name}_Adapter.ToSerializer()`,
    );
  }

  private writeModuleInitAdapterInit(record: RecordLocation): void {
    const name = getTypeName(record);

    if (record.record.recordType === "struct") {
      const builderName = `${name}_builder`;
      for (const removedNumber of record.record.removedNumbers) {
        this.lines.push(
          `                ${name}_Adapter.AddRemovedNumber(${removedNumber})`,
        );
      }

      for (const field of record.record.fields) {
        if (!field.type) {
          continue;
        }
        const propertyName = toFieldPropertyName(field, name);
        const fieldType = this.typeSpeller.getFsharpFieldType(field);
        const serExpr = this.typeSpeller.getSerializerExpr(
          field.type,
          "init",
          field.isRecursive,
        );
        this.lines.push(
          `                ${name}_Adapter.AddField<${fieldType}>(${JSON.stringify(field.name.text)}, ${field.number}, ${serExpr}, global.System.Func<${name}, ${fieldType}>(fun x -> x.${propertyName}), global.System.Action<${builderName}, ${fieldType}>(fun b v -> b.${propertyName} <- v), ${JSON.stringify(this.getDocText(field.doc))})`,
        );
      }

      this.lines.push(`                ${name}_Adapter.Finalize_()`);
      return;
    }

    for (const removedNumber of record.record.removedNumbers) {
      this.lines.push(
        `                ${name}_Adapter.AddRemovedNumber(${removedNumber})`,
      );
    }

    const variantInfos = record.record.fields.map((v) => ({
      variant: v,
      caseName: toVariantCaseName(v, name),
    }));

    variantInfos.forEach(({ variant, caseName }, i) => {
      const kindOrdinal = i + 1;
      if (variant.type) {
        const payloadType = this.typeSpeller.getFsharpType(variant.type);
        const serExpr = this.typeSpeller.getSerializerExpr(
          variant.type,
          "init",
        );
        this.lines.push(
          `                ${name}_Adapter.AddWrapperVariant<${payloadType}>(${JSON.stringify(variant.name.text)}, ${variant.number}, ${kindOrdinal}, ${serExpr}, global.System.Func<${payloadType}, ${name}>(fun v -> ${name}.${caseName} v), global.System.Func<${name}, ${payloadType}>(fun x -> match x with | ${name}.${caseName} v -> v | _ -> failwith "unexpected variant"), ${JSON.stringify(this.getDocText(variant.doc))})`,
        );
      } else {
        this.lines.push(
          `                ${name}_Adapter.AddConstantVariant(${JSON.stringify(variant.name.text)}, ${variant.number}, ${kindOrdinal}, ${name}.${caseName}, ${JSON.stringify(this.getDocText(variant.doc))})`,
        );
      }
    });

    this.lines.push(`                ${name}_Adapter.Finalize_()`);
  }

  private getStructFieldNameMap(
    structRecord: RecordLocation,
  ): ReadonlyMap<string, string> {
    const cached = this.fieldNameMapCache.get(structRecord.record.key);
    if (cached) {
      return cached;
    }

    const map = new Map<string, string>();
    const typeName = getTypeName(structRecord);
    for (const field of structRecord.record.fields) {
      if (!field.type) {
        continue;
      }

      const propertyName = toFieldPropertyName(field, typeName);
      map.set(field.name.text, propertyName);
    }
    this.fieldNameMapCache.set(structRecord.record.key, map);
    return map;
  }

  private getFieldPathExtractor(fieldPath: FieldPath): string {
    return fieldPath.path.map((part) => part.name.text).join(".");
  }

  private getFieldPathMemberSuffix(fieldPath: FieldPath): string {
    return fieldPath.path
      .map((part) => convertCase(part.name.text, "UpperCamel"))
      .join("");
  }

  private computeStructIndexerInfos(record: RecordLocation): Array<{
    indexerName: string;
    keyType: string;
    keySelector: string;
    keyExtractor: string;
  }> {
    const keyedArraySpecs =
      this.keyedArrayContext.getKeySpecsForItemStruct(record);
    if (keyedArraySpecs.length === 0) {
      return [];
    }

    const result: Array<{
      indexerName: string;
      keyType: string;
      keySelector: string;
      keyExtractor: string;
    }> = [];

    for (const spec of keyedArraySpecs) {
      const keyType = this.getFsharpMapKeyType(spec.fieldPath.keyType);
      const keySelector = this.getKeySelectorLambda(record, spec.fieldPath);
      if (!keyType || !keySelector) {
        continue;
      }

      result.push({
        indexerName: spec.specName,
        keyType,
        keySelector,
        keyExtractor: this.getFieldPathExtractor(spec.fieldPath),
      });
    }

    return result;
  }

  private getFsharpMapKeyType(
    keyType: PrimitiveType | ResolvedRecordRef,
  ): string | null {
    if (keyType.kind === "primitive") {
      switch (keyType.primitive) {
        case "bool":
          return "bool";
        case "int32":
          return "int";
        case "int64":
          return "int64";
        case "hash64":
          return "uint64";
        case "timestamp":
          return "global.System.DateTimeOffset";
        case "string":
          return "string";
        case "float32":
        case "float64":
        case "bytes":
          return null;
      }
    }

    const recordLocation = this.typeSpeller.recordMap.get(keyType.key);
    if (!recordLocation || recordLocation.record.recordType !== "enum") {
      return null;
    }
    const enumType = this.typeSpeller.getFsharpType(keyType);
    return `${enumType}_Kind`;
  }

  private getKeySelectorLambda(
    itemStruct: RecordLocation,
    fieldPath: FieldPath,
  ): string | null {
    let selectorExpr = "item";
    let currentRecord: RecordLocation | undefined = itemStruct;

    for (const part of fieldPath.path) {
      const partName = part.name.text;
      if (!currentRecord) {
        return null;
      }

      if (currentRecord.record.recordType === "enum") {
        if (partName !== "kind") {
          return null;
        }
        selectorExpr = `${selectorExpr}.Kind`;
        currentRecord = undefined;
        continue;
      }

      const fieldDecl = currentRecord.record.fields.find(
        (field) => field.name.text === partName && field.type !== undefined,
      );
      if (!fieldDecl || !fieldDecl.type) {
        return null;
      }

      const propertyName =
        this.getStructFieldNameMap(currentRecord).get(partName) ??
        convertCase(partName, "UpperCamel");
      selectorExpr = `${selectorExpr}.${propertyName}`;

      let nextType: ResolvedType = fieldDecl.type;
      if (fieldDecl.isRecursive === "hard") {
        selectorExpr = `${selectorExpr}.Value`;
      } else if (fieldDecl.isRecursive === "via-optional") {
        selectorExpr = `(Option.get ${selectorExpr}).Value`;
        if (nextType.kind === "optional") {
          nextType = nextType.other;
        }
      } else if (nextType.kind === "optional") {
        selectorExpr = `(Option.get ${selectorExpr})`;
        nextType = nextType.other;
      }

      if (nextType.kind === "record") {
        currentRecord = this.typeSpeller.recordMap.get(nextType.key);
      } else {
        currentRecord = undefined;
      }
    }

    return `fun item -> ${selectorExpr}`;
  }

  private getDocText(doc: Doc): string {
    const pieces = doc.pieces;
    if (!pieces || pieces.length === 0) {
      return "";
    }
    return pieces
      .map((piece) => {
        const p = piece as {
          kind?: string;
          text?: string;
          nameParts?: readonly { token?: { text?: string } }[];
        };
        if (p.kind === "text") {
          return p.text ?? "";
        }
        if (p.kind === "reference" && p.nameParts) {
          return p.nameParts
            .map((part) => part.token?.text ?? "")
            .filter((name) => name.length > 0)
            .join(".");
        }
        return "";
      })
      .join("")
      .trim();
  }

  private formatDocAsXmlSummary(doc: Doc, indent = "    "): string[] {
    const text = this.getDocText(doc);
    if (!text) {
      return [];
    }

    const escaped = text
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&apos;");

    const lines = escaped.split("\n");
    if (lines.length === 1) {
      return [`${indent}/// <summary>${lines[0]}</summary>`];
    }

    const result: string[] = [];
    result.push(`${indent}/// <summary>`);
    for (const line of lines) {
      result.push(`${indent}/// ${line}`);
    }
    result.push(`${indent}/// </summary>`);
    return result;
  }
}

