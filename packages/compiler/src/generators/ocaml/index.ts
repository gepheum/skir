import {
  type CodeGenerator,
  type Constant,
  type Doc,
  type Field,
  type Method,
  type Module,
  type RecordKey,
  type RecordLocation,
} from "skir-internal";
import { z } from "zod";
import {
  getFlatRecordId,
  getImmediateSubmoduleName,
  getInternalTypeName,
  modulePathToOutputFile,
  toConstantName,
  toMethodName,
  toStructFieldName,
  toVariantCtorName,
} from "./naming.js";
import { TypeSpeller } from "./type_speller.js";

const Config = z.strictObject({});

type Config = z.infer<typeof Config>;

class OcamlCodeGenerator implements CodeGenerator<Config> {
  readonly id = "skir-ocaml-gen";
  readonly configType = Config;

  generateCode(input: CodeGenerator.Input<Config>): CodeGenerator.Output {
    const { recordMap } = input;
    const outputFiles: CodeGenerator.OutputFile[] = [];
    for (const module of input.modules) {
      outputFiles.push({
        path: modulePathToOutputFile(module.path),
        code: new OcamlSourceFileGenerator(module, recordMap).generate(),
      });
    }
    return { files: outputFiles };
  }
}

interface RecordTreeNode {
  record: RecordLocation;
  children: RecordTreeNode[];
}

class OcamlSourceFileGenerator {
  private readonly typeSpeller: TypeSpeller;

  constructor(
    private readonly inModule: Module,
    private readonly recordMap: ReadonlyMap<RecordKey, RecordLocation>,
  ) {
    this.typeSpeller = new TypeSpeller(recordMap, inModule);
  }

  generate(): string {
    const out: string[] = [];

    out.push(
      "(*  ______                        _               _  _  _  *)\n",
      "(*  |  _  \\                      | |             | |(_)| | *)\n",
      "(*  | | | |  ___    _ __    ___  | |_    ___   __| | _ | |_ *)\n",
      "(*  | | | | / _ \\  | '_ \\  / _ \\ | __|  / _ \\ / _` || || __| *)\n",
      "(*  | |/ / | (_) | | | | || (_) || |_  |  __/| (_| || || |_  *)\n",
      "(*  |___/   \\___/  |_| |_| \\___/  \\__|  \\___| \\__,_||_| \\__| *)\n",
      "(*                                                           *)\n",
      "(* Generated by skir-ocaml-gen                               *)\n",
      "(* Home: https://skir.build/docs/ocaml                       *)\n",
      "(*                                                           *)\n",
      "(* Do not edit this file manually.                           *)\n\n",
      '[@@@ocaml.warning "-26-27-30-32-33-34-39-50"]\n\n',
      "module Skir_ = Skir\n",
      "module Lazy_ = Lazy\n\n",
    );

    const records = this.inModule.records;

    if (records.length > 0) {
      // 1. Emit internal mutually recursive type definitions (`type rec__..._ = ... and ...`)
      this.writeInternalTypeDefinitions(records, out);

      // 2. Emit internal lazy default values (`default__<flat>_`)
      this.writeInternalDefaults(records, out);

      // 3. Emit internal mutable builder types, adapters, and serializers (`serializer__<flat>_`)
      this.writeInternalSerializers(records, out);

      // 4. Emit nested public submodules for each record (`module User = struct ... end`)
      const tree = this.buildRecordTree(records);
      for (const node of tree) {
        this.writeRecordSubmodule(node, out, "");
      }
    }

    // 5. Constants
    for (const constant of this.inModule.constants) {
      this.writeConstant(constant, out);
    }

    // 6. Methods
    for (const method of this.inModule.methods) {
      this.writeMethod(method, out);
    }

    return out.join("");
  }

  private buildRecordTree(
    records: readonly RecordLocation[],
  ): RecordTreeNode[] {
    const keyToNode = new Map<RecordKey, RecordTreeNode>();
    const roots: RecordTreeNode[] = [];
    for (const rec of records) {
      keyToNode.set(rec.record.key, { record: rec, children: [] });
    }
    for (const rec of records) {
      const node = keyToNode.get(rec.record.key)!;
      if (rec.recordAncestors.length <= 1) {
        roots.push(node);
      } else {
        const parentRecord = rec.recordAncestors.at(-2)!;
        const parentNode = keyToNode.get(parentRecord.key);
        if (parentNode) {
          parentNode.children.push(node);
        } else {
          roots.push(node);
        }
      }
    }
    return roots;
  }

  private writeInternalTypeDefinitions(
    records: readonly RecordLocation[],
    out: string[],
  ): void {
    records.forEach((rec, idx) => {
      const keyword = idx === 0 ? "type" : "and";
      const internalTypeName = getInternalTypeName(rec);

      if (rec.record.recordType === "struct") {
        out.push(`${keyword} ${internalTypeName} = {\n`);
        for (const field of rec.record.fields) {
          const fieldName = toStructFieldName(field.name.text);
          const ocamlType = this.typeSpeller.getFieldOcamlType(field);
          out.push(`  ${fieldName} : ${ocamlType};\n`);
        }
        out.push(`  unrecognized_ : Skir_.unrecognized_fields option;\n`);
        out.push(`}\n\n`);
      } else {
        out.push(`${keyword} ${internalTypeName} =\n`);
        out.push(`  | Unknown of Skir_.unrecognized_variant option\n`);
        for (const variant of rec.record.fields) {
          const ctorName = toVariantCtorName(variant);
          if (variant.type) {
            const payloadType = this.typeSpeller.getOcamlType(variant.type);
            out.push(`  | ${ctorName} of ${payloadType}\n`);
          } else {
            out.push(`  | ${ctorName}\n`);
          }
        }
        out.push(`\n`);
      }
    });
  }

  private writeInternalDefaults(
    records: readonly RecordLocation[],
    out: string[],
  ): void {
    records.forEach((rec, idx) => {
      const keyword = idx === 0 ? "let rec" : "and";
      const internalTypeName = getInternalTypeName(rec);
      const flat = getFlatRecordId(rec);
      if (rec.record.recordType === "enum") {
        out.push(
          `${keyword} default__${flat}_lazy_ : ${internalTypeName} Lazy_.t = lazy (Unknown None : ${internalTypeName})\n`,
        );
      } else {
        out.push(
          `${keyword} default__${flat}_lazy_ : ${internalTypeName} Lazy_.t = lazy ({\n`,
        );
        for (const field of rec.record.fields) {
          const fieldName = toStructFieldName(field.name.text);
          const defExpr = this.typeSpeller.getFieldDefaultExpression(
            field,
            true,
          );
          out.push(`  ${fieldName} = ${defExpr};\n`);
        }
        out.push(`  unrecognized_ = None;\n`);
        out.push(`} : ${internalTypeName})\n`);
      }
    });
    out.push(`\n`);

    for (const rec of records) {
      const internalTypeName = getInternalTypeName(rec);
      const flat = getFlatRecordId(rec);
      out.push(
        `let default__${flat}_ : ${internalTypeName} = Lazy_.force default__${flat}_lazy_\n`,
      );
    }
    out.push(`\n`);
  }

  private writeInternalSerializers(
    records: readonly RecordLocation[],
    out: string[],
  ): void {
    for (const rec of records) {
      const internalTypeName = getInternalTypeName(rec);
      const flat = getFlatRecordId(rec);
      const recordId = `${rec.modulePath}:${rec.recordAncestors.map((a) => a.name.text).join(".")}`;
      const docStr = JSON.stringify(docToCommentText(rec.record.doc));

      if (rec.record.recordType === "struct") {
        const mutTypeName = `mut__${flat}_`;
        out.push(`type ${mutTypeName} = {\n`);
        for (const field of rec.record.fields) {
          const fieldName = toStructFieldName(field.name.text);
          const ocamlType = this.typeSpeller.getFieldOcamlType(field);
          out.push(`  mutable mut_${fieldName} : ${ocamlType};\n`);
        }
        out.push(
          `  mutable mut_unrecognized_ : Skir_.unrecognized_fields option;\n`,
        );
        out.push(`}\n\n`);

        out.push(`let adapter__${flat}_ =\n`);
        out.push(`  Skir_.Internal.make_struct_adapter\n`);
        out.push(`    ~record_id:${JSON.stringify(recordId)}\n`);
        out.push(`    ~doc:${docStr}\n`);
        out.push(`    ~default:default__${flat}_\n`);
        out.push(`    ~new_mutable:(fun () -> {\n`);
        for (const field of rec.record.fields) {
          const fieldName = toStructFieldName(field.name.text);
          const defExpr = this.typeSpeller.getFieldDefaultExpression(field);
          out.push(`      mut_${fieldName} = ${defExpr};\n`);
        }
        out.push(`      mut_unrecognized_ = None;\n`);
        out.push(`    })\n`);
        out.push(
          `    ~to_frozen:(fun (m : ${mutTypeName}) : ${internalTypeName} -> {\n`,
        );
        for (const field of rec.record.fields) {
          const fieldName = toStructFieldName(field.name.text);
          out.push(`      ${fieldName} = m.mut_${fieldName};\n`);
        }
        out.push(`      unrecognized_ = m.mut_unrecognized_;\n`);
        out.push(`    })\n`);
        out.push(
          `    ~get_unrecognized:(fun (x : ${internalTypeName}) -> x.unrecognized_)\n`,
        );
        out.push(
          `    ~set_unrecognized:(fun (m : ${mutTypeName}) u -> m.mut_unrecognized_ <- u)\n\n`,
        );
      } else {
        out.push(`let adapter__${flat}_ =\n`);
        out.push(`  Skir_.Internal.make_enum_adapter\n`);
        out.push(`    ~record_id:${JSON.stringify(recordId)}\n`);
        out.push(`    ~doc:${docStr}\n`);
        out.push(`    ~default:default__${flat}_\n`);
        out.push(`    ~get_kind_ordinal:(fun (x : ${internalTypeName}) ->\n`);
        out.push(`      match x with\n`);
        out.push(`      | Unknown _ -> 0\n`);
        let ord = 1;
        for (const variant of rec.record.fields) {
          const ctorName = toVariantCtorName(variant);
          if (variant.type) {
            out.push(`      | ${ctorName} _ -> ${ord}\n`);
          } else {
            out.push(`      | ${ctorName} -> ${ord}\n`);
          }
          ord++;
        }
        out.push(`    )\n`);
        out.push(
          `    ~wrap_unrecognized:(fun u : ${internalTypeName} -> Unknown (Some u))\n`,
        );
        out.push(`    ~get_unrecognized:(fun (x : ${internalTypeName}) ->\n`);
        out.push(`      match x with\n`);
        out.push(`      | Unknown u -> u\n`);
        if (rec.record.fields.length > 0) {
          out.push(`      | _ -> None\n`);
        }
        out.push(`    )\n\n`);
      }
    }

    for (const rec of records) {
      const internalTypeName = getInternalTypeName(rec);
      const flat = getFlatRecordId(rec);
      const adapterFn =
        rec.record.recordType === "struct"
          ? "Skir_.Internal.struct_serializer"
          : "Skir_.Internal.enum_serializer";
      out.push(
        `let serializer_raw__${flat}_ () : ${internalTypeName} Skir_.serializer =\n`,
      );
      out.push(`  ${adapterFn} adapter__${flat}_\n\n`);
    }

    out.push(`let init_serializers_lazy_ : unit Lazy_.t = lazy (\n`);
    for (const rec of records) {
      const internalTypeName = getInternalTypeName(rec);
      const flat = getFlatRecordId(rec);
      if (rec.record.recordType === "struct") {
        const mutTypeName = `mut__${flat}_`;
        for (const field of rec.record.fields) {
          const fieldName = toStructFieldName(field.name.text);
          const serExpr = this.getInitFieldSerializerExpr(field);
          out.push(`  Skir_.Internal.add_struct_field adapter__${flat}_\n`);
          out.push(`    ~name:${JSON.stringify(field.name.text)}\n`);
          out.push(`    ~number:${field.number}\n`);
          out.push(`    ~serializer:(${serExpr})\n`);
          out.push(
            `    ~getter:(fun (x : ${internalTypeName}) -> x.${fieldName})\n`,
          );
          out.push(
            `    ~setter:(fun (m : ${mutTypeName}) v -> m.mut_${fieldName} <- v)\n`,
          );
          out.push(
            `    ~doc:${JSON.stringify(docToCommentText(field.doc))};\n`,
          );
        }
        for (const rem of rec.record.removedNumbers) {
          out.push(
            `  Skir_.Internal.add_struct_removed_number adapter__${flat}_ ${rem};\n`,
          );
        }
        out.push(`  Skir_.Internal.finalize_struct adapter__${flat}_;\n`);
      } else {
        let ord = 1;
        for (const variant of rec.record.fields) {
          const ctorName = toVariantCtorName(variant);
          if (!variant.type) {
            out.push(
              `  Skir_.Internal.add_enum_constant_variant adapter__${flat}_\n`,
            );
            out.push(`    ~name:${JSON.stringify(variant.name.text)}\n`);
            out.push(`    ~number:${variant.number}\n`);
            out.push(`    ~kind_ordinal:${ord}\n`);
            out.push(
              `    ~doc:${JSON.stringify(docToCommentText(variant.doc))}\n`,
            );
            out.push(`    ~instance:(${ctorName} : ${internalTypeName});\n`);
          } else {
            const serExpr = this.getInitTypeSerializerExpr(variant.type);
            const defExpr = this.typeSpeller.getDefaultExpression(variant.type);
            out.push(
              `  Skir_.Internal.add_enum_wrapper_variant adapter__${flat}_\n`,
            );
            out.push(`    ~name:${JSON.stringify(variant.name.text)}\n`);
            out.push(`    ~number:${variant.number}\n`);
            out.push(`    ~kind_ordinal:${ord}\n`);
            out.push(`    ~serializer:(${serExpr})\n`);
            out.push(
              `    ~doc:${JSON.stringify(docToCommentText(variant.doc))}\n`,
            );
            out.push(
              `    ~wrap:(fun v : ${internalTypeName} -> ${ctorName} v)\n`,
            );
            out.push(
              `    ~get_value:(fun (x : ${internalTypeName}) -> match x with ${ctorName} v -> v | _ -> ${defExpr});\n`,
            );
          }
          ord++;
        }
        for (const rem of rec.record.removedNumbers) {
          out.push(
            `  Skir_.Internal.add_enum_removed_number adapter__${flat}_ ${rem};\n`,
          );
        }
        out.push(`  Skir_.Internal.finalize_enum adapter__${flat}_;\n`);
      }
    }
    out.push(`  ()\n`);
    out.push(`)\n\n`);

    for (const rec of records) {
      const internalTypeName = getInternalTypeName(rec);
      const flat = getFlatRecordId(rec);
      out.push(
        `let serializer__${flat}_ () : ${internalTypeName} Skir_.serializer =\n`,
      );
      out.push(`  Lazy_.force init_serializers_lazy_;\n`);
      out.push(`  serializer_raw__${flat}_ ()\n\n`);
    }
  }

  private writeRecordSubmodule(
    node: RecordTreeNode,
    out: string[],
    indent: string,
  ): void {
    const rec = node.record;
    const modName = getImmediateSubmoduleName(rec);
    const internalTypeName = getInternalTypeName(rec);
    const flat = getFlatRecordId(rec);
    const inner = `${indent}  `;

    const doc = commentify(docToCommentText(rec.record.doc), indent);
    if (doc) out.push(doc);

    out.push(`${indent}module ${modName} = struct\n`);

    // 1. Emit nested child submodules first
    for (const child of node.children) {
      this.writeRecordSubmodule(child, out, inner);
    }

    if (rec.record.recordType === "struct") {
      // Type re-export
      out.push(`${inner}type t = ${internalTypeName} = {\n`);
      for (const field of rec.record.fields) {
        const fDoc = commentify(docToCommentText(field.doc), `${inner}  `);
        if (fDoc) out.push(fDoc);
        const fieldName = toStructFieldName(field.name.text);
        const ocamlType = this.typeSpeller.getFieldOcamlType(field);
        out.push(`${inner}  ${fieldName} : ${ocamlType};\n`);
      }
      out.push(`${inner}  unrecognized_ : Skir_.unrecognized_fields option;\n`);
      out.push(`${inner}}\n\n`);

      // default
      out.push(`${inner}let default : t = default__${flat}_\n\n`);

      // make
      out.push(`${inner}let make\n`);
      for (const field of rec.record.fields) {
        const fieldName = toStructFieldName(field.name.text);
        const ocamlType = this.typeSpeller.getFieldOcamlType(field);
        const defExpr = this.typeSpeller.getFieldDefaultExpression(field);
        out.push(`${inner}    ?(${fieldName} : ${ocamlType} = ${defExpr})\n`);
      }
      out.push(`${inner}    () : t =\n`);
      out.push(`${inner}  {\n`);
      for (const field of rec.record.fields) {
        const fieldName = toStructFieldName(field.name.text);
        out.push(`${inner}    ${fieldName};\n`);
      }
      out.push(`${inner}    unrecognized_ = None;\n`);
      out.push(`${inner}  }\n\n`);

      // copy
      out.push(`${inner}let copy\n`);
      for (const field of rec.record.fields) {
        const fieldName = toStructFieldName(field.name.text);
        const ocamlType = this.typeSpeller.getFieldOcamlType(field);
        out.push(`${inner}    ?(${fieldName} : ${ocamlType} option)\n`);
      }
      out.push(`${inner}    (orig_ : t) : t =\n`);
      out.push(`${inner}  {\n`);
      for (const field of rec.record.fields) {
        const fieldName = toStructFieldName(field.name.text);
        out.push(
          `${inner}    ${fieldName} = (match ${fieldName} with Some v -> v | None -> orig_.${fieldName});\n`,
        );
      }
      out.push(`${inner}    unrecognized_ = orig_.unrecognized_;\n`);
      out.push(`${inner}  }\n\n`);

      // Hard-recursive getters
      for (const field of rec.record.fields) {
        if (field.isRecursive !== "hard") continue;
        const fieldName = toStructFieldName(field.name.text);
        const unwrappedType = this.typeSpeller.getOcamlType(field.type!);
        const defExpr = this.typeSpeller.getDefaultExpression(field.type!);
        out.push(`${inner}let get_${fieldName} (s : t) : ${unwrappedType} =\n`);
        out.push(`${inner}  match s.${fieldName} with\n`);
        out.push(`${inner}  | Skir_.Default -> ${defExpr}\n`);
        out.push(`${inner}  | Skir_.Value v -> v\n\n`);
      }

      // serializer
      out.push(
        `${inner}let serializer () : t Skir_.serializer = serializer__${flat}_ ()\n`,
      );
    } else {
      // Enum type re-export
      out.push(`${inner}type t = ${internalTypeName} =\n`);
      out.push(`${inner}  | Unknown of Skir_.unrecognized_variant option\n`);
      for (const variant of rec.record.fields) {
        const vDoc = commentify(docToCommentText(variant.doc), `${inner}  `);
        if (vDoc) out.push(vDoc);
        const ctorName = toVariantCtorName(variant);
        if (variant.type) {
          const payloadType = this.typeSpeller.getOcamlType(variant.type);
          out.push(`${inner}  | ${ctorName} of ${payloadType}\n`);
        } else {
          out.push(`${inner}  | ${ctorName}\n`);
        }
      }
      out.push(`\n`);

      // kind type and function
      out.push(`${inner}type kind =\n`);
      out.push(`${inner}  | Kind_unknown\n`);
      for (const variant of rec.record.fields) {
        const ctorName = toVariantCtorName(variant);
        out.push(`${inner}  | Kind_${ctorName}\n`);
      }
      out.push(`\n`);

      out.push(`${inner}let kind (v : t) : kind =\n`);
      out.push(`${inner}  match v with\n`);
      out.push(`${inner}  | Unknown _ -> Kind_unknown\n`);
      for (const variant of rec.record.fields) {
        const ctorName = toVariantCtorName(variant);
        if (variant.type) {
          out.push(`${inner}  | ${ctorName} _ -> Kind_${ctorName}\n`);
        } else {
          out.push(`${inner}  | ${ctorName} -> Kind_${ctorName}\n`);
        }
      }
      out.push(`\n`);

      // unknown / default
      out.push(`${inner}let unknown : t = default__${flat}_\n`);
      out.push(`${inner}let default : t = default__${flat}_\n\n`);

      // serializer
      out.push(
        `${inner}let serializer () : t Skir_.serializer = serializer__${flat}_ ()\n`,
      );
    }

    out.push(`${indent}end\n\n`);
  }

  private getInitFieldSerializerExpr(field: Field): string {
    if (field.isRecursive === "hard") {
      return `Skir_.recursive_serializer (fun () -> ${this.getInitTypeSerializerExpr(field.type!)})`;
    }
    return this.getInitTypeSerializerExpr(field.type!);
  }

  private getInitTypeSerializerExpr(type: Field["type"] & {}): string {
    switch (type.kind) {
      case "record": {
        const loc = this.recordMap.get(type.key)!;
        if (loc.modulePath === this.inModule.path) {
          return `serializer_raw__${getFlatRecordId(loc)}_ ()`;
        }
        return this.typeSpeller.getSerializerExpression(type);
      }
      case "array": {
        const itemSer = this.getInitTypeSerializerExpr(type.item);
        if (type.key) {
          const keyExtractor = JSON.stringify(
            type.key.path.map((p) => p.name.text).join("."),
          );
          return `Skir_.keyed_list_serializer (${itemSer}) ~key_extractor:${keyExtractor}`;
        }
        return `Skir_.list_serializer (${itemSer})`;
      }
      case "optional": {
        const otherSer = this.getInitTypeSerializerExpr(type.other);
        return `Skir_.optional_serializer (${otherSer})`;
      }
      case "primitive":
        return this.typeSpeller.getSerializerExpression(type);
    }
  }

  private writeConstant(constant: Constant, out: string[]): void {
    if (!constant.type || constant.valueAsDenseJson === undefined) return;
    const doc = commentify(docToCommentText(constant.doc));
    if (doc) out.push(doc);
    const constName = toConstantName(constant.name.text);
    const ocamlType = this.typeSpeller.getOcamlType(constant.type, true);
    const serExpr = this.typeSpeller.getSerializerExpression(constant.type);
    const jsonCode = JSON.stringify(JSON.stringify(constant.valueAsDenseJson));
    out.push(`let ${constName} : ${ocamlType} =\n`);
    out.push(`  match Skir_.from_json_code (${serExpr}) ${jsonCode} with\n`);
    out.push(`  | Ok v -> v\n`);
    out.push(
      `  | Error msg -> failwith ("Failed to initialize constant ${constName}: " ^ msg)\n\n`,
    );
  }

  private writeMethod(method: Method, out: string[]): void {
    if (!method.requestType || !method.responseType) return;
    const doc = commentify(docToCommentText(method.doc));
    if (doc) out.push(doc);
    const methodName = toMethodName(method.name.text);
    const reqType = this.typeSpeller.getOcamlType(method.requestType, true);
    const respType = this.typeSpeller.getOcamlType(method.responseType, true);
    const reqSer = this.typeSpeller.getSerializerExpression(method.requestType);
    const respSer = this.typeSpeller.getSerializerExpression(
      method.responseType,
    );
    out.push(
      `let ${methodName} : (${reqType}, ${respType}) Skir_.Method.t = {\n`,
    );
    out.push(`  name = ${JSON.stringify(method.name.text)};\n`);
    out.push(`  number = ${method.number}L;\n`);
    out.push(`  request_serializer = ${reqSer};\n`);
    out.push(`  response_serializer = ${respSer};\n`);
    out.push(`  doc = ${JSON.stringify(docToCommentText(method.doc))};\n`);
    out.push(`}\n\n`);
  }
}

function docToCommentText(doc: Doc): string {
  return doc.pieces
    .map((p) => {
      switch (p.kind) {
        case "text":
          return p.text;
        case "reference":
          return "`" + p.referenceRange.text.slice(1, -1) + "`";
      }
    })
    .join("");
}

function commentify(text: string, indent = ""): string {
  const trimmed = text.trim().replace(/\(\*/g, "( *").replace(/\*\)/g, "* )");
  if (!trimmed) return "";
  const lines = trimmed.split("\n");
  if (lines.length === 1) {
    return `${indent}(* ${lines[0]} *)\n`;
  }
  return (
    `${indent}(* ${lines[0]}\n` +
    lines
      .slice(1)
      .map((l) => (l.length > 0 ? `${indent}   ${l}` : ""))
      .join("\n") +
    ` *)\n`
  );
}

export const GENERATOR = new OcamlCodeGenerator();
