import {
  type CodeGenerator,
  type Constant,
  type Doc,
  type Field,
  type Method,
  type Module,
  type RecordKey,
  type RecordLocation,
  type ResolvedType,
  convertCase,
  simpleHash,
} from "skir-internal";
import { z } from "zod";
import {
  getKindConstantName,
  getWrapperClassName,
  Namer,
  SCALA_HARD_KEYWORDS,
  toEnumConstantName,
} from "./naming.js";
import { TypeSpeller } from "./type_speller.js";

const Config = z.strictObject({
  packagePrefix: z
    .string()
    .regex(/^([a-z_][a-z0-9_]*\.)*$/)
    .optional(),
});

type Config = z.infer<typeof Config>;

class ScalaCodeGenerator implements CodeGenerator<Config> {
  readonly id = "skir-scala-gen";
  readonly configType = Config;

  generateCode(input: CodeGenerator.Input<Config>): CodeGenerator.Output {
    const { recordMap, config } = input;
    const outputFiles: CodeGenerator.OutputFile[] = [];
    for (const module of input.modules) {
      outputFiles.push({
        path: module.path
          .replace(/^@/, "external/")
          .replace(/-/g, "_")
          .replace(/\.skir$/, ".scala"),
        code: new ScalaSourceFileGenerator(
          module,
          recordMap,
          config,
        ).generate(),
      });
    }
    return { files: outputFiles };
  }

  symbols(input: CodeGenerator.Input<Config>): CodeGenerator.SymbolProvider {
    const namer = new Namer(input.config.packagePrefix ?? "");
    // Fully qualified references compile without imports.
    const symbol = (reference: string): CodeGenerator.Symbol => ({
      reference,
      imports: [],
    });
    const record = (location: RecordLocation): string =>
      namer.getClassName(location).qualifiedName;
    return {
      record: (location): CodeGenerator.Symbol => symbol(record(location)),
      method: (module, method): CodeGenerator.Symbol => {
        const methodName = SCALA_HARD_KEYWORDS.has(method.name.text)
          ? `${method.name.text}_`
          : method.name.text;
        return symbol(
          `_root_.${namer.modulePackage(module.path)}.${methodName}`,
        );
      },
      variant: (location, variant): CodeGenerator.Symbol =>
        symbol(`${record(location)}.Kind.${getKindConstantName(variant)}`),
      variantConstructor: (location, variant): CodeGenerator.Symbol =>
        symbol(
          variant.type
            ? `${record(location)}.${getWrapperClassName(variant)}({value})`
            : `${record(location)}.${toEnumConstantName(variant)}`,
        ),
      variantValue: (location, variant): CodeGenerator.Symbol => {
        if (!variant.type) {
          throw new TypeError(`${variant.name.text} is a constant variant`);
        }
        return symbol(
          `({value}.asInstanceOf[${record(location)}.${getWrapperClassName(variant)}]).value`,
        );
      },
    };
  }
}

// Generates the code for one Scala file.
class ScalaSourceFileGenerator {
  constructor(
    private readonly inModule: Module,
    recordMap: ReadonlyMap<RecordKey, RecordLocation>,
    config: Config,
  ) {
    this.packagePrefix = config.packagePrefix ?? "";
    this.namer = new Namer(this.packagePrefix);
    this.typeSpeller = new TypeSpeller(recordMap, this.namer);
    this.pkgLastSegment = this.namer.modulePackageLastSegment(
      this.inModule.path,
    );
  }

  generate(): string {
    // http://patorjk.com/software/taag/#f=Doom&t=Do%20not%20edit
    this.push(
      `//  ______                        _               _  _  _
      //  |  _  \\                      | |             | |(_)| |
      //  | | | |  ___    _ __    ___  | |_    ___   __| | _ | |_
      //  | | | | / _ \\  | '_ \\  / _ \\ | __|  / _ \\ / _\` || || __|
      //  | |/ / | (_) | | | | || (_) || |_  |  __/| (_| || || |_ 
      //  |___/   \\___/  |_| |_| \\___/  \\__|  \\___| \\__,_||_| \\__|
      //
      // Generated by skir-scala-gen
      // Home: https://skir.build/docs/scala
      //
      // To install the Skir client library, add:
      //   implementation("build.skir:skir-client:latest.release")
      // to your build.gradle.kts / build.gradle file

      `,
      `package ${this.namer.modulePackage(this.inModule.path)}\n\n`,
    );

    this.writeClassesForRecords(
      this.inModule.records.filter(
        // Only retain top-level records.
        // Nested records will be processed from within their ancestors.
        (r: RecordLocation) => r.recordAncestors.length === 1,
      ),
    );

    for (const method of this.inModule.methods) {
      this.writeMethod(method);
    }

    for (const constant of this.inModule.constants) {
      this.writeConstant(constant);
    }

    this.writeSerializerRegistry();

    return this.joinLinesAndFixFormatting();
  }

  private writeSerializerRegistry(): void {
    const records = this.inModule.records
      .slice()
      .sort((left, right) =>
        this.namer
          .getClassName(left)
          .qualifiedName.localeCompare(
            this.namer.getClassName(right).qualifiedName,
          ),
      );
    this.push(
      `\nprivate[${this.pkgLastSegment}] object _SerializerRegistry {\n`,
    );
    for (const record of records) {
      const { qualifiedName } = this.namer.getClassName(record);
      const serializerName = this.typeSpeller.getRegistrySerializerName(record);
      if (record.record.recordType === "struct") {
        this.push(
          `val ${serializerName}Impl: _root_.build.skir.internal.StructSerializer[\n${qualifiedName},\n${qualifiedName}.Mutable,\n] = new _root_.build.skir.internal.StructSerializer[\n${qualifiedName},\n${qualifiedName}.Mutable,\n](\n`,
          `"${getRecordId(record)}",\n`,
          `${toScalaStringLiteral(record.record.doc.text)},\n`,
          `${qualifiedName}.partial(),\n`,
          `(_it: ${qualifiedName}) => if (_it != null) _it.toMutable() else new ${qualifiedName}.Mutable(),\n`,
          `(_it: ${qualifiedName}.Mutable) => _it.toFrozen(),\n`,
          `(_it: ${qualifiedName}) => _it._unrecognizedFields,\n`,
          `(_m: ${qualifiedName}.Mutable, _u: _root_.build.skir.internal.UnrecognizedFields[${qualifiedName}]) => {\n`,
          "_m._unrecognizedFields = _u\n",
          "_root_.kotlin.Unit.INSTANCE\n",
          "},\n",
          ")\n\n",
        );
      } else {
        this.push(
          `val ${serializerName}Impl: _root_.build.skir.internal.EnumSerializer[\n${qualifiedName}\n] =\n`,
          `_root_.build.skir.internal.EnumSerializer.Companion.create[\n${qualifiedName},\n${qualifiedName}.Unknown,\n](\n`,
          `"${getRecordId(record)}",\n`,
          `${toScalaStringLiteral(record.record.doc.text)},\n`,
          `(_it: ${qualifiedName}) => _root_.java.lang.Integer.valueOf(_it.kind.ordinal),\n`,
          `${qualifiedName}.Kind.values.length,\n`,
          `${qualifiedName}.UNKNOWN,\n`,
          `(_it: _root_.build.skir.internal.UnrecognizedVariant[${qualifiedName}]) => new ${qualifiedName}.Unknown(${qualifiedName}.Kind.UNKNOWN, _it),\n`,
          `(_it: ${qualifiedName}.Unknown) => _it._unrecognized,\n`,
          ")\n\n",
        );
      }
      this.push(
        `val ${serializerName}: _root_.build.skir.Serializer[${qualifiedName}] = _root_.build.skir.internal.SerializersKt.makeSerializer(${serializerName}Impl)\n\n`,
      );
    }
    for (const record of records) {
      this.writeSerializerFinalization(record);
    }
    this.push("}\n");
  }

  private writeSerializerFinalization(record: RecordLocation): void {
    const { namer, typeSpeller } = this;
    const { qualifiedName } = namer.getClassName(record);
    const serializerImpl =
      typeSpeller.getRegistrySerializerName(record) + "Impl";
    for (const field of record.record.fields) {
      if (record.record.recordType === "struct") {
        const fieldName = namer.structFieldToScalaName(field);
        const boxedType = typeSpeller.getScalaType(field.type!, "boxed");
        this.push(
          `${serializerImpl}.addField[${boxedType}](\n`,
          `"${field.name.text}",\n`,
          `"${fieldName}",\n`,
          `${field.number},\n`,
          `${typeSpeller.getSerializerExpression(field.type!, this.inModule.path)},\n`,
          `${toScalaStringLiteral(field.doc.text)},\n`,
          `(_it: ${qualifiedName}) => (_it.${fieldName} : ${boxedType}),\n`,
          `(_mut: ${qualifiedName}.Mutable, _v: ${boxedType}) => {\n`,
          `_mut.${fieldName} = _v\n`,
          "_root_.kotlin.Unit.INSTANCE\n",
          "},\n",
          ")\n",
        );
      } else if (!field.type) {
        const constantName = toEnumConstantName(field);
        this.push(
          `${serializerImpl}.addConstantVariant(\n`,
          `${field.number},\n`,
          `"${field.name.text}",\n`,
          `${qualifiedName}.Kind.${getKindConstantName(field)}.ordinal,\n`,
          `${toScalaStringLiteral(field.doc.text)},\n`,
          `${qualifiedName}.${constantName},\n`,
          ")\n",
        );
      } else {
        const wrapperClassName = getWrapperClassName(field);
        const boxedType = typeSpeller.getScalaType(field.type, "boxed");
        this.push(
          `${serializerImpl}.addWrapperVariant[\n${qualifiedName}.${wrapperClassName},\n${boxedType},\n](\n`,
          `${field.number},\n`,
          `"${field.name.text}",\n`,
          `${qualifiedName}.Kind.${getKindConstantName(field)}.ordinal,\n`,
          `${typeSpeller.getSerializerExpression(field.type, this.inModule.path)},\n`,
          `${toScalaStringLiteral(field.doc.text)},\n`,
          `(_it: ${boxedType}) => new ${qualifiedName}.${wrapperClassName}(_it),\n`,
          `(_it: ${qualifiedName}.${wrapperClassName}) => (_it.value: ${boxedType}),\n`,
          ")\n",
        );
      }
    }
    for (const removedNumber of record.record.removedNumbers) {
      this.push(`${serializerImpl}.addRemovedNumber(${removedNumber})\n`);
    }
    this.push(
      `${serializerImpl}.${record.record.recordType === "struct" ? "finalizeStruct" : "finalizeEnum"}()\n\n`,
    );
  }

  private writeClassesForRecords(
    recordLocations: readonly RecordLocation[],
  ): void {
    for (const record of recordLocations) {
      const { recordType } = record.record;
      this.pushEol();
      if (recordType === "struct") {
        this.writeClassesForStruct(record);
      } else {
        this.writeClassForEnum(record);
      }
    }
  }

  private writeClassesForStruct(struct: RecordLocation): void {
    const { namer, typeSpeller, pkgLastSegment } = this;
    const { recordMap } = typeSpeller;
    const { fields } = struct.record;
    const className = namer.getClassName(struct);
    const { qualifiedName } = className;

    // 1. Sealed trait <Struct>_OrMutable
    this.push(`sealed trait ${className.name}_OrMutable {\n`);
    for (const field of fields) {
      const fieldName = namer.structFieldToScalaName(field);
      const allRecordsFrozen = field.isRecursive === "hard";
      const type = typeSpeller.getScalaType(
        field.type!,
        "maybe-mutable",
        allRecordsFrozen,
      );
      this.push(commentify(docToCommentText(field.doc)));
      this.push(`def ${withColon(fieldName)} ${type}\n`);
    }
    this.push(`\ndef toFrozen(): ${qualifiedName}\n`);
    this.push("}\n\n");

    // 2. Frozen final class <Struct>
    this.push(
      commentify([docToCommentText(struct.record.doc), "\nDeeply immutable."]),
      `final class ${className.name} private[${pkgLastSegment}] (\n`,
    );
    for (const field of fields) {
      const fieldName = namer.structFieldToScalaName(field);
      const type = typeSpeller.getScalaType(field.type!, "frozen");
      if (field.isRecursive === "hard") {
        this.push(`private val ${withColon("__" + fieldName)} ${type},\n`);
      } else {
        this.push(`override val ${withColon(fieldName)} ${type},\n`);
      }
    }
    this.push(
      `private[${pkgLastSegment}] val _unrecognizedFields: _root_.build.skir.internal.UnrecognizedFields[${qualifiedName}] = null,\n`,
      `) extends ${qualifiedName}_OrMutable {\n`,
    );
    for (const field of fields) {
      if (field.isRecursive === "hard") {
        const fieldName = namer.structFieldToScalaName(field);
        const type = typeSpeller.getScalaType(field.type!, "frozen");
        const defaultExpr = this.getDefaultExpression(field.type!);
        this.push(
          `override def ${withColon(fieldName)} ${type} =\nif (this.__${fieldName} != null) this.__${fieldName} else ${defaultExpr}\n`,
        );
      }
    }
    this.pushEol();
    this.push(
      `override def toFrozen(): ${qualifiedName} = this\n\n`,
      "/** Returns a mutable shallow copy of this instance. */\n",
      `def toMutable(): ${qualifiedName}.Mutable =\nnew ${qualifiedName}.Mutable(\n`,
    );
    for (const field of fields) {
      const fieldName = namer.structFieldToScalaName(field);
      this.push(`${fieldName} = this.${fieldName},\n`);
    }
    this.push(")\n\n");

    if (fields.length > 0) {
      this.push(
        "/** Returns a shallow copy of this instance with the specified fields replaced. */\n",
        "def copy(\n",
      );
      for (const field of fields) {
        const fieldName = namer.structFieldToScalaName(field);
        const type = typeSpeller.getScalaType(field.type!, "initializer");
        this.push(`${withColon(fieldName)} ${type} = this.${fieldName},\n`);
      }
      this.push(
        `): ${qualifiedName} = {\n`,
        `val _result = new ${qualifiedName}(\n`,
      );
      for (const field of fields) {
        const fieldName = namer.structFieldToScalaName(field);
        this.push(this.toFrozenExpression(fieldName, field.type!), ",\n");
      }
      this.push(
        "this._unrecognizedFields,\n",
        ")\n",
        "if (_result == this) this else _result\n",
        "}\n\n",
      );
    } else {
      this.push(
        "/** Returns a shallow copy of this instance. */\n",
        `def copy(): ${qualifiedName} = this\n\n`,
      );
    }

    this.push(
      "override def equals(_other: _root_.scala.Any): _root_.scala.Boolean =\n",
      `(this eq _other.asInstanceOf[_root_.scala.AnyRef]) || (\n`,
      `_other.isInstanceOf[${qualifiedName}]`,
    );
    if (fields.length > 0) {
      this.push(
        " && {\n",
        `val _that = _other.asInstanceOf[${qualifiedName}]\n`,
        fields
          .map(
            (f) =>
              `this.${namer.structFieldToScalaName(f)} == _that.${namer.structFieldToScalaName(f)}`,
          )
          .join(" && "),
        "\n}\n",
      );
    } else {
      this.push("\n");
    }
    this.push(
      ")\n\n",
      "override def hashCode(): _root_.scala.Int =\n",
      "_root_.java.util.Objects.hash(",
      fields
        .map(
          (f) =>
            `(this.${namer.structFieldToScalaName(f)} : ${typeSpeller.getScalaType(f.type!, "boxed")})`,
        )
        .join(", "),
      ")\n\n",
      "override def toString(): _root_.java.lang.String =\n",
      `_SerializerRegistry.${typeSpeller.getRegistrySerializerName(struct)}.toJsonCode(\nthis,\n_root_.build.skir.JsonFlavor.READABLE,\n)\n`,
      "}\n\n",
    );

    // 3. Companion object <Struct>
    this.push(
      `object ${className.name} {\n`,
      `/** Default instance of \`${className.name}\` with all fields set to their default values. */\n`,
      `val default: ${qualifiedName} =\nnew ${qualifiedName}(\n`,
    );
    for (const field of fields) {
      this.push(
        field.isRecursive === "hard"
          ? "null"
          : this.getDefaultExpression(field.type!),
        ",\n",
      );
    }
    this.push("null,\n", ")\n\n");

    // apply(...)
    if (fields.length > 0) {
      this.push("def apply(\n");
      for (const field of fields) {
        const fieldName = namer.structFieldToScalaName(field);
        const type = typeSpeller.getScalaType(field.type!, "initializer");
        this.push(`${withColon(fieldName)} ${type},\n`);
      }
      this.push(`): ${qualifiedName} =\nnew ${qualifiedName}(\n`);
      for (const field of fields) {
        const fieldName = namer.structFieldToScalaName(field);
        this.push(this.toFrozenExpression(fieldName, field.type!), ",\n");
      }
      this.push("null,\n", ")\n\n");
    } else {
      this.push(`def apply(): ${qualifiedName} = default\n\n`);
    }

    // partial(...)
    if (fields.length > 0) {
      this.push(
        "/**\n",
        ` * Creates a new instance of \`${className.name}\`.\n`,
        " * Unlike `apply`, does not require all fields to be specified.\n",
        " * Missing fields will be set to their default values.\n",
        " */\n",
        "def partial(\n",
      );
      for (const field of fields) {
        const fieldName = namer.structFieldToScalaName(field);
        const type = typeSpeller.getScalaType(field.type!, "initializer");
        const defaultExpr = this.getDefaultExpression(field.type!);
        this.push(`${withColon(fieldName)} ${type} = ${defaultExpr},\n`);
      }
      this.push(
        `): ${qualifiedName} = {\n`,
        `val _result = new ${qualifiedName}(\n`,
      );
      for (const field of fields) {
        const fieldName = namer.structFieldToScalaName(field);
        this.push(this.toFrozenExpression(fieldName, field.type!), ",\n");
      }
      this.push(
        "null,\n",
        ")\n",
        "if (_result == default) default else _result\n",
        "}\n\n",
      );
    } else {
      this.push(
        "/** Returns an instance with all fields set to their default values. */\n",
        `def partial(): ${qualifiedName} = default\n\n`,
      );
    }

    // serializer & typeDescriptor
    this.push(
      `/** Serializer for \`${className.name}\` instances. */\n`,
      `def serializer: _root_.build.skir.Serializer[${qualifiedName}] =\n_SerializerRegistry.${typeSpeller.getRegistrySerializerName(struct)}\n\n`,
      `/** Describes the \`${className.name}\` type. Provides runtime introspection capabilities. */\n`,
      `def typeDescriptor: _root_.build.skir.reflection.StructDescriptor.Reflective[\n${qualifiedName},\n${qualifiedName}.Mutable,\n] =\n_SerializerRegistry.${typeSpeller.getRegistrySerializerName(struct)}Impl.getTypeDescriptor\n\n`,
    );

    // Mutable class
    this.push(
      `/** Mutable version of \`${className.name}\`. */\n`,
      "final class Mutable(\n",
    );
    for (const field of fields) {
      const fieldName = namer.structFieldToScalaName(field);
      const allRecordsFrozen = !!field.isRecursive;
      const type = typeSpeller.getScalaType(
        field.type!,
        "maybe-mutable",
        allRecordsFrozen,
      );
      const defaultExpr = this.getDefaultExpression(field.type!);
      this.push(`var ${withColon(fieldName)} ${type} = ${defaultExpr},\n`);
    }
    this.push(
      `) extends ${qualifiedName}_OrMutable {\n`,
      `private[${pkgLastSegment}] var _unrecognizedFields: _root_.build.skir.internal.UnrecognizedFields[${qualifiedName}] = null\n\n`,
      "/** Returns a deeply immutable copy of this instance. */\n",
      `override def toFrozen(): ${qualifiedName} =\nnew ${qualifiedName}(\n`,
    );
    for (const field of fields) {
      const fieldName = namer.structFieldToScalaName(field);
      const allRecordsFrozen = !!field.isRecursive;
      const expr = allRecordsFrozen
        ? `this.${fieldName}`
        : this.toFrozenExpression(`this.${fieldName}`, field.type!);
      this.push(`${expr},\n`);
    }
    this.push("this._unrecognizedFields,\n", ")\n\n");
    this.writeMutableGetters(fields);
    this.push("}\n"); // class Mutable

    // Nested records inside companion object
    const nestedRecords = struct.record.nestedRecords.map((r) =>
      recordMap.get(r.key)!,
    );
    this.writeClassesForRecords(nestedRecords);

    this.push("}\n\n"); // companion object
  }

  private writeMutableGetters(fields: readonly Field[]): void {
    const { namer, typeSpeller } = this;
    for (const field of fields) {
      if (field.isRecursive) {
        continue;
      }
      const type = field.type!;
      const fieldName = namer.structFieldToScalaName(field);
      const mutableGetterName =
        "mutable" + convertCase(field.name.text, "UpperCamel");
      const mutableType = typeSpeller.getScalaType(field.type!, "mutable");
      const accessor = `this.${fieldName}`;
      let bodyLines: string[] = [];
      if (type.kind === "array") {
        const itemMaybeMutableType = typeSpeller.getScalaType(
          type.item,
          "maybe-mutable",
          false,
          true,
        );
        bodyLines = [
          `${accessor} match {\n`,
          `case _m: _root_.build.skir.internal.MutableList[?] =>\n`,
          `_m.asInstanceOf[${mutableType}]\n`,
          "case _v =>\n",
          `val _m = new _root_.build.skir.internal.MutableList[${itemMaybeMutableType}](_v)\n`,
          `${accessor} = _m\n`,
          "_m\n",
          "}\n",
        ];
      } else if (type.kind === "record") {
        const record = this.typeSpeller.recordMap.get(type.key)!;
        if (record.record.recordType === "struct") {
          const structQualifiedName = namer.getClassName(record).qualifiedName;
          bodyLines = [
            `${accessor} match {\n`,
            `case _f: ${structQualifiedName} =>\n`,
            "val _m = _f.toMutable()\n",
            `${accessor} = _m\n`,
            "_m\n",
            `case _m: ${structQualifiedName}.Mutable =>\n`,
            "_m\n",
            "}\n",
          ];
        }
      }
      if (bodyLines.length) {
        this.push(
          "/**\n",
          ` * If the value of \`${fieldName}\` is already mutable, returns it as-is.\n`,
          ` * Otherwise, makes a mutable copy, assigns it back to \`${fieldName}\` and returns it.\n`,
          " */\n",
          `def ${mutableGetterName}: ${mutableType} =\n`,
        );
        for (const line of bodyLines) {
          this.push(line);
        }
        this.pushEol();
      }
    }
  }

  private writeClassForEnum(record: RecordLocation): void {
    const { namer, typeSpeller, pkgLastSegment } = this;
    const { recordMap } = typeSpeller;
    const { fields: variants } = record.record;
    const constantVariants = variants.filter((v) => !v.type);
    const wrapperVariants = variants.filter((v) => v.type);
    const className = namer.getClassName(record);
    const { qualifiedName } = className;

    // 1. Sealed abstract class <Enum>
    this.push(
      commentify([docToCommentText(record.record.doc), "\nDeeply immutable."]),
      `sealed abstract class ${className.name} private[${pkgLastSegment}] () {\n`,
      `private[${pkgLastSegment}] def _unrecognized: _root_.build.skir.internal.UnrecognizedVariant[${qualifiedName}] = null\n\n`,
      `def kind: ${qualifiedName}.Kind\n\n`,
      "override def toString(): _root_.java.lang.String =\n",
      `_SerializerRegistry.${typeSpeller.getRegistrySerializerName(record)}.toJsonCode(\nthis,\n_root_.build.skir.JsonFlavor.READABLE,\n)\n`,
      "}\n\n",
    );

    // 2. Companion object <Enum>
    this.push(
      `object ${className.name} {\n`,
      `/** The kind of variant held by a \`${className.name}\`. */\n`,
      "enum Kind {\n",
      "case UNKNOWN\n",
    );
    for (const variant of constantVariants) {
      this.push(`case ${getKindConstantName(variant)}\n`);
    }
    for (const variant of wrapperVariants) {
      this.push(`case ${getKindConstantName(variant)}\n`);
    }
    this.push(
      "}\n\n",
      `final class Unknown private[${pkgLastSegment}] (\n`,
      `private[${pkgLastSegment}] val _kind: ${qualifiedName}.Kind,\n`,
      `override private[${pkgLastSegment}] val _unrecognized: _root_.build.skir.internal.UnrecognizedVariant[${qualifiedName}],\n`,
      `) extends ${qualifiedName} {\n`,
      `override def kind: ${qualifiedName}.Kind = this._kind\n\n`,
      "override def equals(_other: _root_.scala.Any): _root_.scala.Boolean =\n",
      `_other.isInstanceOf[${qualifiedName}] && _other.asInstanceOf[${qualifiedName}].kind == this._kind\n\n`,
      "override def hashCode(): _root_.scala.Int =\n",
      "this._kind.ordinal\n",
      "}\n\n",
      commentify([
        `Constant indicating an unknown \`${className.name}\`.`,
        `Default value for fields of type \`${className.name}\`.`,
      ]),
      `val UNKNOWN: ${qualifiedName}.Unknown = new ${qualifiedName}.Unknown(${qualifiedName}.Kind.UNKNOWN, null)\n\n`,
    );

    // Constant variants
    for (const constantVariant of constantVariants) {
      const kindExpr = `${qualifiedName}.Kind.${getKindConstantName(constantVariant)}`;
      const constantName = toEnumConstantName(constantVariant);
      this.push(
        commentify(docToCommentText(constantVariant.doc)),
        `object ${constantName} extends ${qualifiedName} {\n`,
        `override def kind: ${qualifiedName}.Kind = ${kindExpr}\n\n`,
        "override def equals(_other: _root_.scala.Any): _root_.scala.Boolean =\n",
        `_other.isInstanceOf[${qualifiedName}] && _other.asInstanceOf[${qualifiedName}].kind == ${kindExpr}\n\n`,
        "override def hashCode(): _root_.scala.Int =\n",
        `${kindExpr}.ordinal\n`,
        "}\n\n",
      );
    }

    // Wrapper variants
    for (const wrapperVariant of wrapperVariants) {
      const valueType = wrapperVariant.type!;
      const wrapperClassName = getWrapperClassName(wrapperVariant);
      const initializerType = typeSpeller.getScalaType(
        valueType,
        "initializer",
      );
      const frozenType = typeSpeller.getScalaType(valueType, "frozen");
      const kindExpr = `${qualifiedName}.Kind.${getKindConstantName(wrapperVariant)}`;

      this.push(commentify(docToCommentText(wrapperVariant.doc)));
      if (initializerType === frozenType) {
        this.push(
          `final class ${wrapperClassName}(\n`,
          `val value: ${frozenType},\n`,
          `) extends ${qualifiedName} {\n`,
        );
      } else {
        this.push(
          `final class ${wrapperClassName}(\n`,
          `_value: ${initializerType},\n`,
          `) extends ${qualifiedName} {\n`,
          `val value: ${frozenType} = ${this.toFrozenExpression("_value", valueType)}\n\n`,
        );
      }
      this.push(
        `override def kind: ${qualifiedName}.Kind = ${kindExpr}\n\n`,
        "override def equals(_other: _root_.scala.Any): _root_.scala.Boolean =\n",
        `_other.isInstanceOf[${qualifiedName}.${wrapperClassName}] && this.value == _other.asInstanceOf[${qualifiedName}.${wrapperClassName}].value\n\n`,
        "override def hashCode(): _root_.scala.Int =\n",
        "this.value.hashCode() + (",
        String(simpleHash(wrapperVariant.name.text) | 0),
        ")\n",
        "}\n",
        `object ${wrapperClassName} {\n`,
        `def apply(value: ${initializerType}): ${qualifiedName}.${wrapperClassName} =\nnew ${qualifiedName}.${wrapperClassName}(value)\n\n`,
        `def unapply(_w: ${qualifiedName}.${wrapperClassName}): _root_.scala.Some[${frozenType}] =\n_root_.scala.Some(_w.value)\n`,
        "}\n\n",
      );
    }

    // createX helpers for struct wrapper variants
    for (const wrapperVariant of wrapperVariants) {
      const type = wrapperVariant.type!;
      if (type.kind !== "record") {
        continue;
      }
      const structLocation = typeSpeller.recordMap.get(type.key)!;
      const struct = structLocation.record;
      if (struct.recordType !== "struct") {
        continue;
      }
      const structClassName = namer.getClassName(structLocation);
      const createFunName =
        "create" + convertCase(wrapperVariant.name.text, "UpperCamel");
      const wrapperClassName = getWrapperClassName(wrapperVariant);
      this.push(
        `/** Shortcut for \`${wrapperClassName}(${structClassName.name}(...))\`. */\n`,
        `def ${createFunName}(\n`,
      );
      for (const field of struct.fields) {
        const fieldName = namer.structFieldToScalaName(field);
        const fieldType = typeSpeller.getScalaType(field.type!, "initializer");
        this.push(`${withColon(fieldName)} ${fieldType},\n`);
      }
      this.push(
        `): ${qualifiedName}.${wrapperClassName} =\nnew ${qualifiedName}.${wrapperClassName}(\n`,
        `${structClassName.qualifiedName}(\n`,
      );
      for (const field of struct.fields) {
        const fieldName = namer.structFieldToScalaName(field);
        this.push(`${fieldName} = ${fieldName},\n`);
      }
      this.push(")\n", ")\n\n");
    }

    // serializer & typeDescriptor
    this.push(
      `/** Serializer for \`${className.name}\` instances. */\n`,
      `def serializer: _root_.build.skir.Serializer[${qualifiedName}] =\n_SerializerRegistry.${typeSpeller.getRegistrySerializerName(record)}\n\n`,
      `/** Describes the \`${className.name}\` type. Provides runtime introspection capabilities. */\n`,
      `def typeDescriptor: _root_.build.skir.reflection.EnumDescriptor.Reflective[${qualifiedName}] =\n_SerializerRegistry.${typeSpeller.getRegistrySerializerName(record)}Impl.getTypeDescriptor\n`,
    );

    // Nested records inside companion object
    const nestedRecords = record.record.nestedRecords.map((r) =>
      recordMap.get(r.key)!,
    );
    this.writeClassesForRecords(nestedRecords);

    this.push("}\n\n"); // companion object
  }

  private writeMethod(method: Method): void {
    const { typeSpeller } = this;
    const rawMethodName = method.name.text;
    const methodName = SCALA_HARD_KEYWORDS.has(rawMethodName)
      ? `${rawMethodName}_`
      : rawMethodName;
    const requestType = typeSpeller.getScalaType(method.requestType!, "boxed");
    const requestSerializerExpr = typeSpeller.getSerializerExpression(
      method.requestType!,
      null,
    );
    const responseType = typeSpeller.getScalaType(
      method.responseType!,
      "boxed",
    );
    const responseSerializerExpr = typeSpeller.getSerializerExpression(
      method.responseType!,
      null,
    );
    this.push(
      commentify(docToCommentText(method.doc)),
      `lazy val ${methodName}: _root_.build.skir.service.Method[\n${requestType},\n${responseType},\n] =\n`,
      "new _root_.build.skir.service.Method(\n",
      `"${rawMethodName}",\n`,
      `${method.number}L,\n`,
      requestSerializerExpr + ",\n",
      responseSerializerExpr + ",\n",
      toScalaStringLiteral(method.doc.text) + ",\n",
      ")\n\n",
    );
  }

  private writeConstant(constant: Constant): void {
    const { typeSpeller } = this;
    const name = constant.name.text;
    const type = constant.type!;
    const scalaType = typeSpeller.getScalaType(type, "frozen");
    const tryGetScalaConstLiteral: () => string | undefined = () => {
      if (type.kind !== "primitive") {
        return undefined;
      }
      const { valueAsDenseJson } = constant;
      switch (type.primitive) {
        case "bool":
          return JSON.stringify(!!valueAsDenseJson);
        case "int32":
          return JSON.stringify(valueAsDenseJson);
        case "string":
          return toScalaStringLiteral(String(valueAsDenseJson));
        case "int64":
          return `${valueAsDenseJson}L`;
        case "hash64":
          return (
            BigInt.asIntN(64, BigInt(String(valueAsDenseJson))).toString() + "L"
          );
        case "float32": {
          if (valueAsDenseJson === "NaN") {
            return "_root_.scala.Float.NaN";
          } else if (valueAsDenseJson === "Infinity") {
            return "_root_.scala.Float.PositiveInfinity";
          } else if (valueAsDenseJson === "-Infinity") {
            return "_root_.scala.Float.NegativeInfinity";
          } else {
            return JSON.stringify(valueAsDenseJson) + "F";
          }
        }
        case "float64": {
          if (valueAsDenseJson === "NaN") {
            return "_root_.scala.Double.NaN";
          } else if (valueAsDenseJson === "Infinity") {
            return "_root_.scala.Double.PositiveInfinity";
          } else if (valueAsDenseJson === "-Infinity") {
            return "_root_.scala.Double.NegativeInfinity";
          } else {
            return JSON.stringify(valueAsDenseJson);
          }
        }
        default:
          return undefined;
      }
    };
    this.push(commentify(docToCommentText(constant.doc)));
    const scalaConstLiteral = tryGetScalaConstLiteral();
    if (scalaConstLiteral !== undefined) {
      this.push(`val ${name}: ${scalaType} = ${scalaConstLiteral}\n\n`);
    } else {
      const serializerExpression = typeSpeller.getSerializerExpression(
        constant.type!,
        null,
      );
      const jsonStringLiteral = toScalaStringLiteral(
        JSON.stringify(constant.valueAsDenseJson),
      );
      this.push(
        `lazy val ${name}: ${scalaType} =\n`,
        serializerExpression,
        `.fromJsonCode(${jsonStringLiteral})\n\n`,
      );
    }
  }

  private getDefaultExpression(type: ResolvedType): string {
    switch (type.kind) {
      case "primitive": {
        switch (type.primitive) {
          case "bool":
            return "false";
          case "int32":
            return "0";
          case "int64":
          case "hash64":
            return "0L";
          case "float32":
            return "0.0F";
          case "float64":
            return "0.0";
          case "timestamp":
            return "_root_.java.time.Instant.EPOCH";
          case "string":
            return '""';
          case "bytes":
            return "_root_.okio.ByteString.EMPTY";
        }
        break;
      }
      case "array": {
        const itemType = this.typeSpeller.getScalaType(type.item, "boxed");
        if (type.key) {
          const { keyType } = type.key;
          let scalaKeyType = this.typeSpeller.getScalaType(keyType, "boxed");
          if (keyType.kind === "record") {
            scalaKeyType += ".Kind";
          }
          return `_root_.build.skir.internal.FrozenListKt.emptyKeyedList[${itemType}, ${scalaKeyType}]()`;
        } else {
          return `_root_.build.skir.internal.FrozenListKt.emptyFrozenList[${itemType}]()`;
        }
      }
      case "optional": {
        const otherType = this.typeSpeller.getScalaType(type.other, "boxed");
        return `_root_.java.util.Optional.empty[${otherType}]()`;
      }
      case "record": {
        const record = this.typeSpeller.recordMap.get(type.key)!;
        const scalaType = this.typeSpeller.getScalaType(type, "frozen");
        switch (record.record.recordType) {
          case "struct": {
            return `${scalaType}.default`;
          }
          case "enum": {
            return `${scalaType}.UNKNOWN`;
          }
        }
        break;
      }
    }
  }

  private toFrozenExpression(
    inputExpr: string,
    type: ResolvedType,
    depth = 0,
  ): string {
    const { namer, typeSpeller } = this;
    const it = `_it${depth}`;
    switch (type.kind) {
      case "primitive": {
        return inputExpr;
      }
      case "array": {
        const itemInitType = typeSpeller.getScalaType(
          type.item,
          "initializer",
          undefined,
          true,
        );
        const itemBoxedType = typeSpeller.getScalaType(
          type.item,
          "boxed",
          undefined,
          true,
        );
        const itemToFrozenExpr = this.toFrozenExpression(
          it,
          type.item,
          depth + 1,
        );
        if (type.key) {
          const path = type.key.path
            .map((f) => namer.structFieldToScalaName(f.name.text))
            .join(".");
          const { keyType } = type.key;
          let keyBoxedType = typeSpeller.getScalaType(
            keyType,
            "boxed",
            undefined,
            true,
          );
          if (keyType.kind === "record") {
            keyBoxedType += ".Kind";
          }
          if (itemToFrozenExpr === it) {
            return `_root_.build.skir.internal.FrozenListKt.toKeyedList(${inputExpr}, "${path}", (${it}: ${itemBoxedType}) => (${it}.${path} : ${keyBoxedType}))`;
          } else {
            return `_root_.build.skir.internal.FrozenListKt.toKeyedList(${inputExpr}, "${path}", (${it}: ${itemBoxedType}) => (${it}.${path} : ${keyBoxedType}), (${it}: ${itemInitType}) => ${itemToFrozenExpr})`;
          }
        } else {
          if (itemToFrozenExpr === it) {
            return `_root_.build.skir.internal.FrozenListKt.toFrozenList(${inputExpr})`;
          } else {
            return `_root_.build.skir.internal.FrozenListKt.toFrozenList(${inputExpr}, (${it}: ${itemInitType}) => ${itemToFrozenExpr})`;
          }
        }
      }
      case "optional": {
        const otherExpr = this.toFrozenExpression(it, type.other, depth + 1);
        if (otherExpr === it) {
          return inputExpr;
        } else {
          const otherBoxedType = typeSpeller.getScalaType(
            type.other,
            "boxed",
            undefined,
            true,
          );
          return `${inputExpr}.map[${otherBoxedType}]((${it}) => ${otherExpr})`;
        }
      }
      case "record": {
        const record = this.typeSpeller.recordMap.get(type.key)!;
        if (record.record.recordType === "struct") {
          return `${inputExpr}.toFrozen()`;
        } else {
          return inputExpr;
        }
      }
    }
  }

  private push(...code: string[]): void {
    this.code += code.join("");
  }

  private pushEol(): void {
    this.code += "\n";
  }

  private joinLinesAndFixFormatting(): string {
    const indentUnit = "  ";
    let result = "";
    const contextStack: Array<"{" | "(" | "[" | "="> = [];
    const peakTop = (): string | undefined => contextStack.at(-1);
    const getMatchingLeftBracket = (r: "}" | ")" | "]"): "{" | "(" | "[" => {
      switch (r) {
        case "}":
          return "{";
        case ")":
          return "(";
        case "]":
          return "[";
      }
    };
    for (let line of this.code.split("\n")) {
      line = line.trim();
      if (line.length <= 0) {
        result += "\n";
        continue;
      }

      const firstChar = line[0];
      switch (firstChar) {
        case "}":
        case ")":
        case "]": {
          const left = getMatchingLeftBracket(firstChar);
          while (contextStack.pop() !== left) {
            if (contextStack.length <= 0) {
              throw Error();
            }
          }
          break;
        }
      }
      const indent =
        indentUnit.repeat(contextStack.length) +
        (line.startsWith("*") ? " " : "");
      result += `${indent}${line.trimEnd()}\n`;
      if (line.startsWith("/") || line.startsWith("*")) {
        continue;
      }
      const lastChar = line.slice(-1);
      switch (lastChar) {
        case "{":
        case "(":
        case "[": {
          contextStack.push(lastChar);
          break;
        }
        case "=": {
          if (peakTop() !== "=") {
            contextStack.push("=");
          }
          break;
        }
        default: {
          if (peakTop() === "=") {
            contextStack.pop();
          }
          break;
        }
      }
    }

    return result
      .replace(/\{\s+\}/g, "{}")
      .replace(/\(\s+\)/g, "()")
      .replace(/\[\s+\]/g, "[]")
      .replace(/(\{\n *)\n/g, "$1")
      .replace(/\n(\n *\})/g, "$1")
      .replace(/\n\n\n+/g, "\n\n")
      .replace(/\n\n$/g, "\n");
  }

  private readonly typeSpeller: TypeSpeller;
  private readonly packagePrefix: string;
  private readonly namer: Namer;
  private readonly pkgLastSegment: string;
  private code = "";
}

function withColon(ident: string): string {
  return ident.endsWith("_") ? `${ident} :` : `${ident}:`;
}

function getRecordId(struct: RecordLocation): string {
  const modulePath = struct.modulePath;
  const qualifiedRecordName = struct.recordAncestors
    .map((r) => r.name.text)
    .join(".");
  return `${modulePath}:${qualifiedRecordName}`;
}

function toScalaStringLiteral(input: string): string {
  const escaped = input.replace(/[\\"\x00-\x1f\x7f-\xff]/g, (char) => {
    switch (char) {
      case '"':
        return '\\"';
      case "\\":
        return "\\\\";
      case "\b":
        return "\\b";
      case "\f":
        return "\\f";
      case "\n":
        return "\\n";
      case "\r":
        return "\\r";
      case "\t":
        return "\\t";
      default: {
        const code = char.charCodeAt(0).toString(16).padStart(4, "0");
        return `\\u${code}`;
      }
    }
  });
  return `"${escaped}"`;
}

function commentify(textOrLines: string | readonly string[]): string {
  const text = (
    typeof textOrLines === "string" ? textOrLines : textOrLines.join("\n")
  )
    .trim()
    .replace(/\n{3,}/g, "\n\n")
    .replace(/\*\//g, "* /");
  if (text.length <= 0) {
    return "";
  }
  const lines = text.split("\n");
  if (lines.length === 1) {
    return `/** ${text} */\n`;
  } else {
    return ["/**\n", ...lines.map((line) => ` * ${line}\n`), " */\n"].join("");
  }
}

function docToCommentText(doc: Doc): string {
  return doc.pieces
    .map((p) => {
      switch (p.kind) {
        case "text":
          return p.text;
        case "reference":
          return "`" + p.referenceRange.text.slice(1, -1) + "`";
      }
    })
    .join("");
}

