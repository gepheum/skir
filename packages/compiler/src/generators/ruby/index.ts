import * as Paths from "path";
import type {
  CodeGenerator,
  Constant,
  Doc,
  Field,
  Method,
  Module,
  Record,
  RecordKey,
  RecordLocation,
  ResolvedType,
} from "skir-internal";
import { convertCase } from "skir-internal";
import { z } from "zod";
import {
  ClassName,
  RUBY_UPPER_CAMEL_KEYWORDS,
  getClassName,
  getRubyModulePath,
  normalizeModuleFilePath,
} from "./class_speller.js";
import { RubyType } from "./ruby_type.js";
import { TypeSpeller } from "./type_speller.js";

const Config = z.strictObject({
  modulePrefix: z
    .string()
    .regex(/^([A-Z][A-Za-z0-9_]*::)*$/)
    .optional(),
});

export type Config = z.infer<typeof Config>;

class RubyCodeGenerator implements CodeGenerator<Config> {
  readonly id = "skir-ruby-gen";
  readonly configType = Config;

  generateCode(input: CodeGenerator.Input<Config>): CodeGenerator.Output {
    const { recordMap, config } = input;
    const outputFiles: CodeGenerator.OutputFile[] = [];
    for (const module of input.modules) {
      outputFiles.push({
        path: normalizeModuleFilePath(module.path),
        code: new RubyModuleCodeGenerator(module, recordMap, config).generate(),
      });
    }
    return { files: outputFiles };
  }
}

class RubyModuleCodeGenerator {
  constructor(
    private readonly inModule: Module,
    recordMap: ReadonlyMap<RecordKey, RecordLocation>,
    private readonly config: Config,
  ) {
    this.typeSpeller = new TypeSpeller(recordMap, inModule, config);
  }

  generate(): string {
    this.pushLine("# typed: strict");
    this.pushLine("# frozen_string_literal: true");
    this.pushLine("#  ______                        _               _  _  _");
    this.pushLine("#  |  _  \\                      | |             | |(_)| |");
    this.pushLine("#  | | | |  ___    _ __    ___  | |_    ___   __| | _ | |_");
    this.pushLine(
      "#  | | | | / _ \\  | '_ \\  / _ \\ | __|  / _ \\ / _` || || __|",
    );
    this.pushLine(
      "#  | |/ / | (_) | | | | || (_) || |_  |  __/| (_| || || |_ ",
    );
    this.pushLine(
      "#  |___/   \\___/  |_| |_| \\___/  \\__|  \\___| \\__,_||_| \\__|",
    );
    this.pushLine("#");
    this.pushLine("# Generated by skir-ruby-gen");
    this.pushLine("# Home: https://skir.build/docs/ruby");
    this.pushLine("#");
    this.pushLine("# To install the Skir client library:");
    this.pushLine("#   gem install skir-client");
    this.pushLine();

    this.writeRequires();

    const modulePath = getRubyModulePath(this.inModule.path, this.config);
    for (const modName of modulePath) {
      this.pushLine(`module ${modName}`);
      this.indent += INDENT_UNIT;
    }

    this.writeClassesForRecords(
      this.inModule.records.filter(
        (r: RecordLocation) => r.recordAncestors.length === 1,
      ),
    );

    for (const method of this.inModule.methods) {
      this.writeMethod(method);
    }

    for (const constant of this.inModule.constants) {
      this.writeConstant(constant);
    }

    this.writeInitModuleCall();

    for (let i = 0; i < modulePath.length; i++) {
      this.dedent();
      this.pushLine("end");
    }

    return this.code;
  }

  private writeRequires(): void {
    this.pushLine('require "sorbet-runtime"');
    this.pushLine('require "skir"');
    const curFile = normalizeModuleFilePath(this.inModule.path);
    const curDir = Paths.posix.dirname(curFile);
    for (const importedPath of Object.keys(this.inModule.pathToImportedNames)) {
      const targetFile = normalizeModuleFilePath(importedPath).replace(
        /\.rb$/,
        "",
      );
      let rel = Paths.posix.relative(curDir, targetFile);
      if (!rel.startsWith(".")) {
        rel = `./${rel}`;
      }
      this.pushLine(`require_relative "${rel}"`);
    }
    this.pushLine();
  }

  private writeClassesForRecords(
    recordLocations: readonly RecordLocation[],
  ): void {
    const { recordMap } = this.typeSpeller;
    for (const record of recordLocations) {
      const { recordType } = record.record;
      this.pushLine();
      if (recordType === "struct") {
        this.writeClassForStruct(record);
      } else {
        this.writeClassForEnum(record);
      }
      const nestedRecords = record.record.nestedRecords.map((r) =>
        recordMap.get(r.key)!,
      );
      this.writeClassesForRecords(nestedRecords);
      this.dedent();
      this.pushLine("end");
    }
  }

  private writeClassForStruct(struct: RecordLocation): void {
    const { typeSpeller } = this;
    const { doc, fields } = struct.record;
    const className = this.getClassName(struct);
    const { qualifiedName: relativeQualifiedName } = className;

    this.pushComment(
      doc,
      `Deeply immutable. If you need mutability, use '${className.name}::Mutable'.`,
    );
    this.pushLine(`class ${className.name}`);
    this.indent += INDENT_UNIT;
    this.pushLine("extend T::Sig");
    this.pushLine("extend T::Helpers");

    // initialize
    this.pushLine();
    if (fields.length > 0) {
      this.pushLine("sig do");
      this.indent += INDENT_UNIT;
      this.pushLine("params(");
      this.indent += INDENT_UNIT;
      this.writeStructFieldsSigParams(struct.record, "initializer", false);
      this.dedent();
      this.pushLine(").void.checked(:never)");
      this.dedent();
      this.pushLine("end");
      const initArgs = fields
        .map((f) => `${structFieldToAttr(f.name.text)}:`)
        .join(", ");
      this.pushLine(`def initialize(${initArgs}); end`);
    } else {
      this.pushLine("sig { void.checked(:never) }");
      this.pushLine("def initialize; end");
    }

    // partial
    this.pushLine();
    if (fields.length > 0) {
      this.pushLine("sig do");
      this.indent += INDENT_UNIT;
      this.pushLine("params(");
      this.indent += INDENT_UNIT;
      this.writeStructFieldsSigParams(struct.record, "initializer", false);
      this.dedent();
      this.pushLine(`).returns(${relativeQualifiedName}).checked(:never)`);
      this.dedent();
      this.pushLine("end");
      const partialArgs = fields
        .map((f) => `${structFieldToAttr(f.name.text)}: T.unsafe(nil)`)
        .join(", ");
      this.pushLine(`def self.partial(${partialArgs}); T.unsafe(nil); end`);
    } else {
      this.pushLine(
        `sig { returns(${relativeQualifiedName}).checked(:never) }`,
      );
      this.pushLine("def self.partial; T.unsafe(nil); end");
    }

    // replace
    this.pushLine();
    if (fields.length > 0) {
      this.pushLine("sig do");
      this.indent += INDENT_UNIT;
      this.pushLine("params(");
      this.indent += INDENT_UNIT;
      this.writeStructFieldsSigParams(struct.record, "initializer", true);
      this.dedent();
      this.pushLine(`).returns(${relativeQualifiedName}).checked(:never)`);
      this.dedent();
      this.pushLine("end");
      const replaceArgs = fields
        .map((f) => `${structFieldToAttr(f.name.text)}: Skir::KEEP`)
        .join(", ");
      this.pushLine(`def replace(${replaceArgs}); T.unsafe(nil); end`);
    } else {
      this.pushLine(
        `sig { returns(${relativeQualifiedName}).checked(:never) }`,
      );
      this.pushLine("def replace; T.unsafe(nil); end");
    }

    // getters
    for (const field of fields) {
      const attribute = structFieldToAttr(field.name.text);
      const rbType = typeSpeller.getRubyType(field.type!, "frozen");
      this.pushLine();
      this.pushComment(field.doc);
      this.pushLine(`sig { returns(${rbType}).checked(:never) }`);
      this.pushLine(`def ${attribute}; T.unsafe(nil); end`);
    }

    // to_frozen & to_mutable
    this.pushLine();
    this.pushLine(`sig { returns(${relativeQualifiedName}).checked(:never) }`);
    this.pushLine("def to_frozen; self; end");
    this.pushLine();
    this.pushLine(
      `sig { returns(${relativeQualifiedName}::Mutable).checked(:never) }`,
    );
    this.pushLine("def to_mutable; T.unsafe(nil); end");

    // Mutable class
    this.pushLine();
    this.pushLine("class Mutable");
    this.indent += INDENT_UNIT;
    this.pushLine("extend T::Sig");
    this.pushLine("extend T::Helpers");

    this.pushLine();
    if (fields.length > 0) {
      this.pushLine("sig do");
      this.indent += INDENT_UNIT;
      this.pushLine("params(");
      this.indent += INDENT_UNIT;
      this.writeStructFieldsSigParams(struct.record, "maybe-mutable", false);
      this.dedent();
      this.pushLine(").void.checked(:never)");
      this.dedent();
      this.pushLine("end");
      const mutInitArgs = fields
        .map((f) => `${structFieldToAttr(f.name.text)}: T.unsafe(nil)`)
        .join(", ");
      this.pushLine(`def initialize(${mutInitArgs}); end`);
    } else {
      this.pushLine("sig { void.checked(:never) }");
      this.pushLine("def initialize; end");
    }

    for (const field of fields) {
      const allRecordsFrozen = !!field.isRecursive;
      const attribute = structFieldToAttr(field.name.text);
      const rbType = typeSpeller.getRubyType(
        field.type!,
        "maybe-mutable",
        allRecordsFrozen,
      );
      this.pushLine();
      this.pushLine(`sig { returns(${rbType}).checked(:never) }`);
      this.pushLine(`def ${attribute}; T.unsafe(nil); end`);
      this.pushLine();
      this.pushLine(
        `sig { params(val: ${rbType}).returns(${rbType}).checked(:never) }`,
      );
      this.pushLine(`def ${attribute}=(val); val; end`);
    }

    for (const field of fields) {
      const fieldType = field.type!;
      const { isRecursive } = field;
      const mutableType = typeSpeller.getRubyType(fieldType, "mutable");
      const hasMutableGetter =
        typeSpeller
          .getRubyType(fieldType, "maybe-mutable", !!isRecursive)
          .toString() !== mutableType.toString();
      if (!hasMutableGetter) continue;
      this.pushLine();
      this.pushLine(`sig { returns(${mutableType}).checked(:never) }`);
      this.pushLine(`def mutable_${field.name.text}; T.unsafe(nil); end`);
    }

    this.pushLine();
    this.pushLine(`sig { returns(${relativeQualifiedName}).checked(:never) }`);
    this.pushLine("def to_frozen; T.unsafe(nil); end");

    this.dedent();
    this.pushLine("end");

    this.pushLine();
    this.pushLine(
      `OrMutable = T.type_alias { T.any(${relativeQualifiedName}, ${relativeQualifiedName}::Mutable) }`,
    );
    this.pushLine();
    this.pushLine(
      `DEFAULT = T.let(T.unsafe(nil), ${relativeQualifiedName}, checked: false)`,
    );
    this.pushLine();
    this.pushLine(
      `sig { returns(Skir::Serializer[${relativeQualifiedName}]).checked(:never) }`,
    );
    this.pushLine("def self.serializer; T.unsafe(nil); end");
  }

  private writeStructFieldsSigParams(
    struct: Record,
    flavor: "initializer" | "maybe-mutable",
    withKeep: boolean,
  ): void {
    const { typeSpeller } = this;
    const { fields } = struct;
    for (let i = 0; i < fields.length; i++) {
      const field = fields[i]!;
      const allRecordsFrozen = !!field.isRecursive;
      let rbType = typeSpeller.getRubyType(
        field.type!,
        flavor,
        allRecordsFrozen,
      );
      if (withKeep) {
        rbType = RubyType.union([rbType, RubyType.KEEP]);
      }
      const attribute = structFieldToAttr(field.name.text);
      const comma = i < fields.length - 1 ? "," : "";
      this.pushLine(`${attribute}: ${rbType}${comma}`);
    }
  }

  private writeClassForEnum(record: RecordLocation): void {
    const { typeSpeller } = this;
    const { doc: enumDoc, fields: variants } = record.record;
    const constantVariants = variants.filter((v) => !v.type);
    const wrapperVariants = variants.filter((v) => v.type);
    const className = this.getClassName(record);
    const { qualifiedName: relativeQualifiedName } = className;

    this.pushComment(enumDoc, "Deeply immutable.");
    this.pushLine(`class ${className.name}`);
    this.indent += INDENT_UNIT;
    this.pushLine("extend T::Sig");
    this.pushLine("extend T::Helpers");
    this.pushLine("sealed!");

    // Variant classes first so constants and Union can reference them
    this.writeEnumVariantClass("UNKNOWN", RubyType.NIL);
    for (const constantVariant of constantVariants) {
      const upperName = convertCase(
        constantVariant.name.text,
        "UPPER_UNDERSCORE",
      );
      this.writeEnumVariantClass(upperName, RubyType.NIL);
    }
    for (const wrapperVariant of wrapperVariants) {
      const vName = wrapperVariant.name.text;
      const vType = typeSpeller.getRubyType(wrapperVariant.type!, "frozen");
      this.writeEnumVariantClass(vName, vType);
    }

    // Constants
    this.pushLine();
    this.pushLine(
      `UNKNOWN = T.let(T.unsafe(nil), ${relativeQualifiedName}::V_UNKNOWN, checked: false)`,
    );
    for (const constantVariant of constantVariants) {
      const upperName = convertCase(
        constantVariant.name.text,
        "UPPER_UNDERSCORE",
      );
      const attribute = enumConstantVariantToAttr(upperName);
      this.pushLine();
      this.pushComment(constantVariant.doc);
      this.pushLine(
        `${attribute} = T.let(T.unsafe(nil), ${relativeQualifiedName}::V_${upperName}, checked: false)`,
      );
    }

    // Wrapper factory methods
    for (const wrapperVariant of wrapperVariants) {
      const name = wrapperVariant.name.text;
      const type = wrapperVariant.type!;
      const rbType = typeSpeller.getRubyType(type, "initializer");
      this.pushLine();
      this.pushComment(wrapperVariant.doc);
      this.pushLine(
        `sig { params(value: ${rbType}).returns(${relativeQualifiedName}::V_${name}).checked(:never) }`,
      );
      this.pushLine(`def self.wrap_${name}(value); T.unsafe(nil); end`);

      if (type.kind === "record") {
        const { record: targetRecord } = typeSpeller.recordMap.get(type.key)!;
        if (targetRecord.recordType === "struct") {
          this.pushLine();
          if (targetRecord.fields.length > 0) {
            this.pushLine("sig do");
            this.indent += INDENT_UNIT;
            this.pushLine("params(");
            this.indent += INDENT_UNIT;
            this.writeStructFieldsSigParams(targetRecord, "initializer", false);
            this.dedent();
            this.pushLine(
              `).returns(${relativeQualifiedName}::V_${name}).checked(:never)`,
            );
            this.dedent();
            this.pushLine("end");
            const createArgs = targetRecord.fields
              .map((f) => `${structFieldToAttr(f.name.text)}:`)
              .join(", ");
            this.pushLine(
              `def self.create_${name}(${createArgs}); T.unsafe(nil); end`,
            );
          } else {
            this.pushLine(
              `sig { returns(${relativeQualifiedName}::V_${name}).checked(:never) }`,
            );
            this.pushLine(`def self.create_${name}; T.unsafe(nil); end`);
          }
        }
      }
    }

    // Union & Kind & methods
    const unionVariantNames = ["V_UNKNOWN"].concat(
      variants.map((v) =>
        v.type
          ? `V_${v.name.text}`
          : `V_${convertCase(v.name.text, "UPPER_UNDERSCORE")}`,
      ),
    );
    const unionTypes = unionVariantNames.map((vn) =>
      RubyType.of(`${relativeQualifiedName}::${vn}`),
    );
    const valueUnionTypes = [RubyType.NIL].concat(
      wrapperVariants.map((wv) => typeSpeller.getRubyType(wv.type!, "frozen")),
    );

    this.pushLine();
    this.pushLine("Kind = T.type_alias { String }");
    this.pushLine(`Union = T.type_alias { ${RubyType.union(unionTypes)} }`);
    this.pushLine();
    this.pushLine("sig { returns(Union).checked(:never) }");
    this.pushLine("def union; T.unsafe(self); end");
    this.pushLine();
    this.pushLine("sig { returns(String).checked(:never) }");
    this.pushLine("def kind; T.unsafe(nil); end");
    this.pushLine();
    this.pushLine(
      `sig { returns(${RubyType.union(valueUnionTypes)}).checked(:never) }`,
    );
    this.pushLine("def value; T.unsafe(nil); end");
    this.pushLine();
    this.pushLine("sig { returns(T::Boolean).checked(:never) }");
    this.pushLine("def unknown?; T.unsafe(nil); end");
    this.pushLine();
    this.pushLine("sig { returns(T::Boolean).checked(:never) }");
    this.pushLine("def present?; T.unsafe(nil); end");
    this.pushLine();
    this.pushLine(
      `sig { returns(Skir::Serializer[${relativeQualifiedName}]).checked(:never) }`,
    );
    this.pushLine("def self.serializer; T.unsafe(nil); end");
  }

  private writeEnumVariantClass(
    variantName: string,
    valueType: RubyType,
  ): void {
    this.pushLine();
    this.pushLine(`class V_${variantName} < self`);
    this.indent += INDENT_UNIT;
    this.pushLine("extend T::Sig");
    this.pushLine("extend T::Helpers");
    this.pushLine("sig { returns(String).checked(:never) }");
    this.pushLine("def kind; T.unsafe(nil); end");
    this.pushLine(`sig { returns(${valueType}).checked(:never) }`);
    this.pushLine("def value; T.unsafe(nil); end");
    this.dedent();
    this.pushLine("end");
  }

  private writeMethod(method: Method): void {
    const { typeSpeller } = this;
    const methodName = method.name.text;
    const varName = RUBY_UPPER_CAMEL_KEYWORDS.has(methodName)
      ? `${methodName}_`
      : methodName;
    const requestType = typeSpeller.getRubyType(method.requestType!, "frozen");
    const responseType = typeSpeller.getRubyType(
      method.responseType!,
      "frozen",
    );
    const methodType = `Skir::Method[${requestType}, ${responseType}]`;
    this.pushLine();
    this.pushComment(method.doc);
    this.pushLine(
      `${varName} = T.let(T.unsafe(nil), ${methodType}, checked: false)`,
    );
  }

  private writeConstant(constant: Constant): void {
    const { typeSpeller } = this;
    const name = constant.name.text;
    const type = typeSpeller.getRubyType(constant.type!, "frozen");
    this.pushLine();
    this.pushComment(constant.doc);
    this.pushLine(`${name} = T.let(T.unsafe(nil), ${type}, checked: false)`);
  }

  private writeInitModuleCall(): void {
    const { inModule, typeSpeller } = this;
    this.pushLine();
    this.pushLine("Skir::Internal.init_module(");
    this.indent += INDENT_UNIT;
    this.pushLine("records: [");
    this.indent += INDENT_UNIT;
    for (const record of inModule.records) {
      const { doc: recordDoc, recordType, removedNumbers } = record.record;
      const className = this.getClassName(record);
      const recordQualname = record.recordAncestors
        .map((r) => r.name.text)
        .join(".");
      const recordId = `${inModule.path}:${recordQualname}`;
      if (recordType === "struct") {
        this.pushLine("Skir::Spec::Struct.new(");
      } else {
        this.pushLine("Skir::Spec::Enum.new(");
      }
      this.indent += INDENT_UNIT;
      this.pushLine(`id: ${JSON.stringify(recordId)},`);
      if (className.name !== record.record.name.text) {
        this.pushLine(`class_name: ${JSON.stringify(className.name)},`);
      }
      this.pushLine(
        `class_qualname: ${JSON.stringify(className.fullRubyQualname)},`,
      );
      if (recordDoc.text) {
        this.pushLine(`doc: ${JSON.stringify(recordDoc.text)},`);
      }
      if (removedNumbers.length) {
        this.pushLine(`removed_numbers: [${removedNumbers.join(", ")}],`);
      }
      if (recordType === "struct") {
        const { fields } = record.record;
        this.pushLine("fields: [");
        this.indent += INDENT_UNIT;
        for (const field of fields) {
          const fieldName = field.name.text;
          const fieldType = field.type!;
          const { doc: fieldDoc, isRecursive } = field;
          const hasMutableGetter =
            typeSpeller
              .getRubyType(fieldType, "mutable", !!isRecursive)
              .toString() !==
            typeSpeller
              .getRubyType(fieldType, "maybe-mutable", !!isRecursive)
              .toString();
          this.pushLine("Skir::Spec::Field.new(");
          this.indent += INDENT_UNIT;
          this.pushLine(`name: ${JSON.stringify(fieldName)},`);
          this.pushLine(`number: ${field.number},`);
          this.pushLine(`type: ${this.typeToSpec(fieldType)},`);
          if (fieldDoc.text) {
            this.pushLine(`doc: ${JSON.stringify(fieldDoc.text)},`);
          }
          if (hasMutableGetter) {
            this.pushLine("has_mutable_getter: true,");
          }
          const attribute = structFieldToAttr(fieldName);
          if (attribute !== fieldName) {
            this.pushLine(`attribute: ${JSON.stringify(attribute)},`);
          }
          this.dedent();
          this.pushLine("),");
        }
        this.dedent();
        this.pushLine("]");
      } else {
        const { fields: variants } = record.record;
        const constantFields = variants.filter((f) => !f.type);
        const wrapperFields = variants.filter((f) => f.type);
        this.pushLine("constant_variants: [");
        this.indent += INDENT_UNIT;
        this.writeConstantVariantsSpec(constantFields);
        this.dedent();
        this.pushLine("],");
        this.pushLine("wrapper_variants: [");
        this.indent += INDENT_UNIT;
        this.writeWrapperVariantsSpec(wrapperFields);
        this.dedent();
        this.pushLine("]");
      }
      this.dedent();
      this.pushLine("),");
    }
    this.dedent();
    this.pushLine("],");

    this.pushLine("methods: [");
    this.indent += INDENT_UNIT;
    for (const method of inModule.methods) {
      const methodName = method.name.text;
      const { doc } = method;
      this.pushLine("Skir::Spec::Method.new(");
      this.indent += INDENT_UNIT;
      this.pushLine(`name: ${JSON.stringify(methodName)},`);
      this.pushLine(`number: ${method.number},`);
      this.pushLine(`request_type: ${this.typeToSpec(method.requestType!)},`);
      this.pushLine(`response_type: ${this.typeToSpec(method.responseType!)},`);
      if (doc.text) {
        this.pushLine(`doc: ${JSON.stringify(doc.text)},`);
      }
      if (RUBY_UPPER_CAMEL_KEYWORDS.has(methodName)) {
        this.pushLine(`var_name: ${JSON.stringify(`${methodName}_`)},`);
      }
      this.dedent();
      this.pushLine("),");
    }
    this.dedent();
    this.pushLine("],");

    this.pushLine("constants: [");
    this.indent += INDENT_UNIT;
    for (const constant of inModule.constants) {
      const jsonCode = JSON.stringify(constant.valueAsDenseJson);
      this.pushLine("Skir::Spec::Constant.new(");
      this.indent += INDENT_UNIT;
      this.pushLine(`name: ${JSON.stringify(constant.name.text)},`);
      this.pushLine(`type: ${this.typeToSpec(constant.type!)},`);
      this.pushLine(`json_code: ${JSON.stringify(jsonCode)}`);
      this.dedent();
      this.pushLine("),");
    }
    this.dedent();
    this.pushLine("],");

    this.pushLine("target: self");
    this.dedent();
    this.pushLine(")");
  }

  private typeToSpec(type: ResolvedType): string {
    switch (type.kind) {
      case "array": {
        const itemSpec = this.typeToSpec(type.item);
        if (!type.key) {
          return `Skir::Spec::ArrayType.new(${itemSpec})`;
        }
        const attributes = type.key.path
          .map((n) => JSON.stringify(structFieldToAttr(n.name.text)))
          .join(", ");
        return `Skir::Spec::ArrayType.new(${itemSpec}, [${attributes}])`;
      }
      case "optional": {
        const otherSpec = this.typeToSpec(type.other);
        return `Skir::Spec::OptionalType.new(${otherSpec})`;
      }
      case "primitive":
        return `Skir::Spec::PrimitiveType::${type.primitive.toUpperCase()}`;
      case "record": {
        const record = this.typeSpeller.recordMap.get(type.key)!;
        const { recordAncestors, modulePath } = record;
        const recordQualname = recordAncestors
          .map((r) => r.name.text)
          .join(".");
        return JSON.stringify(`${modulePath}:${recordQualname}`);
      }
    }
  }

  private writeConstantVariantsSpec(variants: readonly Field[]): void {
    for (const variant of variants) {
      const variantName = convertCase(variant.name.text, "UPPER_UNDERSCORE");
      const { doc: variantDoc } = variant;
      this.pushLine("Skir::Spec::ConstantVariant.new(");
      this.indent += INDENT_UNIT;
      this.pushLine(`name: ${JSON.stringify(variantName)},`);
      this.pushLine(`number: ${variant.number},`);
      if (variantDoc.text) {
        this.pushLine(`doc: ${JSON.stringify(variantDoc.text)},`);
      }
      const attribute = enumConstantVariantToAttr(variantName);
      if (attribute !== variantName) {
        this.pushLine(`attribute: ${JSON.stringify(attribute)},`);
      }
      this.dedent();
      this.pushLine("),");
    }
  }

  private writeWrapperVariantsSpec(variants: readonly Field[]): void {
    for (const variant of variants) {
      const { doc: variantDoc } = variant;
      this.pushLine("Skir::Spec::WrapperVariant.new(");
      this.indent += INDENT_UNIT;
      this.pushLine(`name: ${JSON.stringify(variant.name.text)},`);
      this.pushLine(`number: ${variant.number},`);
      this.pushLine(`type: ${this.typeToSpec(variant.type!)},`);
      if (variantDoc.text) {
        this.pushLine(`doc: ${JSON.stringify(variantDoc.text)},`);
      }
      this.dedent();
      this.pushLine("),");
    }
  }

  private pushComment(doc: Doc, extraLine?: string): void {
    const docText = getDocTextForComment(doc);
    const parts: string[] = [];
    if (docText) {
      parts.push(docText);
    }
    if (extraLine) {
      parts.push(extraLine);
    }
    if (parts.length === 0) return;
    const text = parts.join("\n\n");
    for (const line of text.split("\n")) {
      if (line.trim() === "") {
        this.pushLine("#");
      } else {
        this.pushLine(`# ${line}`);
      }
    }
  }

  private pushLine(code = ""): void {
    if (code === "") {
      this.code += "\n";
      return;
    }
    this.code += `${this.indent}${code}\n`;
  }

  private dedent(): void {
    this.indent = this.indent.substring(
      0,
      this.indent.length - INDENT_UNIT.length,
    );
  }

  private getClassName(record: RecordLocation): ClassName {
    return getClassName(record, this.inModule, this.config);
  }

  private readonly typeSpeller: TypeSpeller;
  private code = "";
  private indent = "";
}

export const GENERATOR = new RubyCodeGenerator();

const INDENT_UNIT = "  ";

function structFieldToAttr(fieldName: string): string {
  return RUBY_LOWER_CASE_KEYWORDS.has(fieldName) ||
    STRUCT_GEN_LOWER_SYMBOLS.has(fieldName) ||
    fieldName.startsWith("mutable_")
    ? `${fieldName}_`
    : fieldName;
}

function enumConstantVariantToAttr(variantName: string): string {
  return ENUM_GEN_UPPER_SYMBOLS.has(variantName) ||
    RUBY_UPPER_CAMEL_KEYWORDS.has(variantName) ||
    variantName.startsWith("V_")
    ? `${variantName}_`
    : variantName;
}

function getDocTextForComment(doc: Doc): string {
  return doc.pieces
    .map((p) => {
      switch (p.kind) {
        case "text":
          return p.text;
        case "reference":
          return `'${p.referenceRange.text.slice(1, -1)}'`;
      }
    })
    .join("");
}

