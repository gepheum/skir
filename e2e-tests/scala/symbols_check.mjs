// A companion generator that references every declaration emitted by
// skir-scala-gen through its symbol provider. Compiling the e2e test sources
// checks that the provider agrees with generateCode.
import { GENERATOR as SCALA } from "../../packages/compiler/dist/generators/scala/index.js";

export const GENERATOR = {
  id: "symbols-check",
  configType: SCALA.configType,
  generateCode(input) {
    const symbols = SCALA.symbols(input);
    const records = [];
    const methods = [];
    const rebuilds = [];
    for (const module of input.modules) {
      for (const location of module.records) {
        const record = symbols.record(location).reference;
        records.push(`classOf[${record}],\n`);
        if (location.record.recordType !== "enum") {
          continue;
        }
        const arms = location.record.fields.map((variant) => {
          const constructor = symbols.variantConstructor(location, variant);
          const value = variant.type
            ? symbols.variantValue(location, variant).reference
            : "";
          const rebuilt = constructor.reference.replace(
            "{value}",
            value.replace("{value}", "self"),
          );
          return `case ${symbols.variant(location, variant).reference} => ${rebuilt}\n`;
        });
        rebuilds.push(
          `extension (self: ${record}) def rebuild(): ${record} =\n`,
          "  self.kind match {\n",
          ...arms.map((a) => `    ${a}`),
          "    case _ => self\n",
          "  }\n\n",
        );
      }
      for (const method of module.methods) {
        methods.push(`${symbols.method(module, method).reference},\n`);
      }
    }
    const code = [
      "// Generated by e2e-test/symbols_check.mjs\n\n",
      "package symbols_check\n\n",
      "val records: _root_.scala.List[_root_.java.lang.Class[?]] = _root_.scala.List(\n",
      ...records,
      ")\n\n",
      "val methods: _root_.scala.List[_root_.scala.Any] = _root_.scala.List(\n",
      ...methods,
      ")\n\n",
      "/** Rebuilds the variant from its own value, through the symbol provider. */\n",
      ...rebuilds,
    ].join("");
    return { files: [{ path: "symbols_check.scala", code }] };
  },
};
